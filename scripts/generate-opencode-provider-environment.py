#!/usr/bin/env python3
"""Generate the provider key variables the pinned OpenCode reads.

OpenCode treats a provider as signed in when one of the variables its catalog
names is set in its own environment. Workers start harnesses with a cleared
environment, so Mjolnir passes those variables through from the environment
it runs in, and needs their names. They come from two places in OpenCode's
source: the `env` lists of the bundled models.dev snapshot, and the literal
`{ type: "env", names: [...] }` methods its built-in plugins register.

Usage: generate-opencode-provider-environment.py <opencode checkout> <version> <output>

Run it against a checkout of the tag Mjolnir pins (`OPENCODE_VERSION` in
mj-core/src/harness_runtime.rs) whenever that pin changes.
"""
import json
from pathlib import Path
import re
import sys

ENV_METHOD = re.compile(r'type:\s*"env",\s*names:\s*\[([^\]]*)\]')
STRING = re.compile(r'"([A-Za-z_][A-Za-z0-9_]*)"')


def snapshot_names(checkout):
    catalog = json.loads((checkout / "packages/core/src/models-dev/snapshot.txt").read_text())
    return {name for provider in catalog.values() for name in provider.get("env", [])}


def plugin_names(checkout):
    names = set()
    for source in sorted((checkout / "packages/core/src/plugin").rglob("*.ts")):
        if ".test." in source.name:
            continue
        for method in ENV_METHOD.finditer(source.read_text()):
            names.update(STRING.findall(method.group(1)))
    return names


def main():
    checkout, version, output = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
    plugins = plugin_names(checkout)
    if not plugins:
        raise SystemExit(f"no plugin env methods found under {checkout}; has the source layout changed?")
    names = sorted(snapshot_names(checkout) | plugins)
    header = [
        f"# OpenCode {version}: the provider key variables it reads from its environment.",
        "# Generated by scripts/generate-opencode-provider-environment.py; do not edit.",
    ]
    output.write_text("\n".join(header + names) + "\n")


if __name__ == "__main__":
    main()
