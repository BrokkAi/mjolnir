// The texts Rust prints for an operating system error on Linux. Rust's
// error_string (std 1.99.1 src/sys/io/error/unix.rs) calls the C library's
// __xpg_strerror_r, so the text is the C library's, and the two C libraries
// Mjolnir is linked against word many errors differently: `mj` uses glibc
// and `mj-worker` uses musl.
//
// Both tables were produced on Linux x86_64 by this program, built once with
// gcc against glibc 2.44 and once with `musl-gcc -static` against musl 1.2.6,
// and run over -3..=140:
//
//	extern int __xpg_strerror_r(int errnum, char *buf, size_t buflen);
//	int main(void) {
//		for (int e = -3; e <= 140; e++) {
//			char buf[128] = {0};
//			int rc = __xpg_strerror_r(e, buf, sizeof buf);
//			printf("%d\t%d\t%s\n", e, rc, buf);
//		}
//	}
//
// Error numbers are the same on every Linux architecture Mjolnir builds for
// (x86_64 and aarch64). glibc is loaded at run time, so a Rust `mj` prints
// the text of the glibc installed on the machine; a newer glibc can know
