func answerIo(request json.RawMessage) any {
	object := decodeRequest(request)
	switch textOf(object["op"]) {
	case "os_error":
		e := rsio.ErrorFromRawOsError(int32(intOf(object["code"])))
		return map[string]any{"error": errJSON(e), "kind_only": errJSON(rsio.ErrorFrom(e.Kind()))}
	case "kind":
		return errJSON(rsio.ErrorFrom(kindsByName[textOf(object["name"])]))
	case "custom":
		e := rsio.ErrorNew(kindsByName[textOf(object["kind"])], textOf(object["message"]))
		var inner, source any
		if value, ok := e.GetRef().Get(); ok {
			inner = value.Error()
		}
		if value := e.Source(); value != nil {
			source = value.Error()
		}
		return map[string]any{"error": errJSON(e), "inner": inner, "source": source}
	case "other":
		return errJSON(rsio.ErrorOther(textOf(object["message"])))
	case "custom_os":
		code := int32(intOf(object["code"]))
		return errJSON(rsio.ErrorNew(kindsByName[textOf(object["kind"])], rsio.ErrorFromRawOsError(code)))
	case "nested":
		kind := kindsByName[textOf(object["kind"])]
		inner := kindsByName[textOf(object["inner"])]
		return map[string]any{
			"error":         errJSON(rsio.ErrorNew(kind, rsio.ErrorNew(inner, textOf(object["message"])))),
			"kind_of_inner": errJSON(rsio.ErrorNew(kind, rsio.ErrorFrom(inner))),
		}
	case "reader":
		return readerOp(object)
	case "writer":
		return writerOp(object)
	case "cursor":
		return cursorOp(object)
	case "copy":
		return copyOp(object)
	}
	panic("unknown op " + textOf(object["op"]))
}

