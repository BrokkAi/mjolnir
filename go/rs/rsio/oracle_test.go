func generateCopies(random *rng, yield func(any)) {
	sizes := []int{0, 1, 100, 8191, 8192, 8193, 16384, 20000}
	for _, readerShape := range []string{"plain", "bufreader", "cursor", "slice", "take"} {
		for _, writerShape := range []string{"plain", "bufwriter", "vec"} {
			for _, size := range sizes {
				reader := map[string]any{
					"shape": readerShape,
					"data":  map[string]any{"lcg": size + 1, "len": size},
					"chunk": pick(random, 0, 0, 1000, 8192, 5),
					"cap":   pick(random, 16, 8192, 8192, 16384),
					"limit": pick(random, 0, 50, 8192, 1000000),
				}
				if readerShape == "plain" || readerShape == "bufreader" {
					switch random.intn(8) {
					case 0:
						reader["fail_at"] = pick(random, 0, 10, 9000)
					case 1:
						reader["interrupt_at"] = pick(random, 0, 10, 9000)
					}
				}
				writer := map[string]any{
					"shape":   writerShape,
					"max":     pick(random, 0, 0, 0, 4096, 100),
					"cap":     pick(random, 16, 8192, 8192, 16384),
					"vec_cap": pick(random, 0, 10, 10000, 30000),
					"prefix":  pick(random, "", hexOf([]byte("already here"))),
				}
				if writerShape != "vec" {
					switch random.intn(8) {
					case 0:
						writer["err_at"] = pick(random, 0, 10, 9000)
					case 1:
						writer["zero_at"] = pick(random, 0, 10, 9000)
					}
				}
				yield(map[string]any{"op": "copy", "reader": reader, "writer": writer})
			}
		}
	}
}

