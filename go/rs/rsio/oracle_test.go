// The differential tests ask the Rust oracle (go/port/oracle, module
// std_io) what std::io does and hold this package against it.
//
// The answers hold the text of operating system errors, which belongs to
// the operating system and its C library, so a corpus is recorded for one
// of them: testdata/oracle/rsio_linux.jsonl.gz is Linux with glibc. On another
// system the test runs when a corpus was recorded there, or against the
// live oracle.

// corpusFor names the corpus of this operating system, and skips the test
// when there is none and none is being made.
func corpusFor(t *testing.T, name string) string {
	t.Helper()
	corpus := name + "_" + runtime.GOOS
	if mode := os.Getenv("MJ_ORACLE"); mode == "record" || mode == "live" {
		return corpus
	}
	for _, suffix := range []string{".jsonl.gz", ".jsonl"} {
		if _, err := os.Stat(filepath.Join("testdata", "oracle", corpus+suffix)); err == nil {
			return corpus
		}
	}
	t.Skipf("no oracle corpus was recorded on %s; record one there with MJ_ORACLE=record", runtime.GOOS)
	return corpus
}

// rng is a small deterministic generator (splitmix64), so that the requests
// do not depend on the Go release.
type rng struct{ state uint64 }

func (r *rng) next() uint64 {
	r.state += 0x9e3779b97f4a7c15
	z := r.state
	z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9
	z = (z ^ (z >> 27)) * 0x94d049bb133111eb
	return z ^ (z >> 31)
}

func (r *rng) intn(n int) int { return int(r.next() % uint64(n)) }

func pick[T any](r *rng, options ...T) T { return options[r.intn(len(options))] }

// --- encoding ------------------------------------------------------------

func hexOf(data []byte) string { return hex.EncodeToString(data) }

// decodeBytes reads bytes of a request: hexadecimal text, or a description
// of generated bytes, as the oracle reads them.
func decodeBytes(value any) []byte {
	switch value := value.(type) {
	case string:
		data, err := hex.DecodeString(value)
		if err != nil {
			panic(err)
		}
		return data
	case map[string]any:
		if seed, ok := value["lcg"]; ok {
			length := int(intOf(value["len"]))
			var alphabet []byte
			if text, ok := value["alphabet"].(string); ok {
				alphabet = decodeBytes(text)
			}
			state := uint64(intOf(seed))
			out := make([]byte, 0, length)
			for i := 0; i < length; i++ {
				state = state*6364136223846793005 + 1442695040888963407
				b := byte(state >> 56)
				if len(alphabet) != 0 {
					b = alphabet[int(b)%len(alphabet)]
				}
				out = append(out, b)
			}
			return out
		}
		unit := decodeBytes(value["repeat"])
		return bytes.Repeat(unit, int(intOf(value["times"])))
	}
	return nil
}

// show writes bytes of a reply as the oracle does: hexadecimal text when
// they are few, and otherwise their length and FNV-1a hash.
func show(data []byte) string {
	if len(data) <= 96 {
		return hexOf(data)
	}
	hash := uint64(0xcbf29ce484222325)
	for _, b := range data {
		hash ^= uint64(b)
		hash *= 0x100000001b3
	}
	return fmt.Sprintf("len:%d:fnv:%016x", len(data), hash)
}

func intOf(value any) int64 {
	switch value := value.(type) {
	case json.Number:
		if n, err := value.Int64(); err == nil {
			return n
		}
		n, err := strconv.ParseUint(value.String(), 10, 64)
		if err != nil {
			panic(err)
		}
		return int64(n)
	case float64:
		return int64(value)
	case int:
		return int64(value)
	case nil:
		return 0
	}
	panic(fmt.Sprintf("not a number: %#v", value))
}

func uintOf(value any) uint64 {
	if number, ok := value.(json.Number); ok {
		n, err := strconv.ParseUint(number.String(), 10, 64)
		if err != nil {
			panic(err)
		}
		return n
	}
	return uint64(intOf(value))
}

// optionalInt is a member that may be absent: -1 then.
func optionalInt(object map[string]any, key string) int {
	value, ok := object[key]
	if !ok || value == nil {
		return -1
	}
	return int(intOf(value))
}

func textOf(value any) string {
	text, _ := value.(string)
	return text
}

func decodeRequest(request json.RawMessage) map[string]any {
	decoder := json.NewDecoder(bytes.NewReader(request))
	decoder.UseNumber()
	var object map[string]any
	if err := decoder.Decode(&object); err != nil {
		panic(err)
	}
	return object
}

// errJSON reports an error the way the oracle reports an io::Error.
func errJSON(err error) map[string]any {
	e := rsio.From(err)
	var raw any
	if code, ok := e.RawOsError().Get(); ok {
		raw = code
	}
	return map[string]any{
		"kind":      e.Kind().DebugString(),
		"kind_text": e.Kind().String(),
		"raw":       raw,
		"display":   e.Error(),
		"debug":     e.DebugString(),
	}
}

func resultJSON(value any, err error) map[string]any {
	if err != nil {
		return map[string]any{"err": errJSON(err)}
	}
	return map[string]any{"ok": value}
}

func unitJSON(err error) map[string]any { return resultJSON(nil, err) }

