// --- readers ---------------------------------------------------------------

// chunked is the oracle's Chunked reader: fixed data handed out at most
// chunk bytes a call, which can fail once or report an interruption once at
// an offset, and which records the size of every buffer it is handed. Its
// Read has Rust's contract: 0 and no error at the end.
type chunked struct {
	data        []byte
	pos         int
	chunk       int
	failAt      int
	interruptAt int
	log         *[]int
}

func newChunked(spec map[string]any, dataKey, chunkKey string, log *[]int) *chunked {
	c := &chunked{
		data:        decodeBytes(spec[dataKey]),
		chunk:       int(intOf(spec[chunkKey])),
		failAt:      -1,
		interruptAt: -1,
		log:         log,
	}
	if dataKey == "data" {
		c.failAt = optionalInt(spec, "fail_at")
		c.interruptAt = optionalInt(spec, "interrupt_at")
	}
	return c
}

func (c *chunked) Read(buf []byte) (int, error) {
	*c.log = append(*c.log, len(buf))
	if c.interruptAt >= 0 && c.pos >= c.interruptAt {
		c.interruptAt = -1
		return 0, rsio.ErrorFrom(rsio.ErrorKind_Interrupted)
	}
	if c.failAt >= 0 && c.pos >= c.failAt {
		c.failAt = -1
		return 0, rsio.ErrorOther("injected read failure")
	}
	n := min(len(buf), len(c.data)-c.pos)
	if c.chunk != 0 {
		n = min(n, c.chunk)
	}
	if c.failAt >= 0 {
		n = min(n, c.failAt-c.pos)
	}
	if c.interruptAt >= 0 {
		n = min(n, c.interruptAt-c.pos)
	}
	copy(buf[:n], c.data[c.pos:c.pos+n])
	c.pos += n
	return n, nil
}

func buildReader(spec map[string]any, log, log2 *[]int) io.Reader {
	first := func() *chunked { return newChunked(spec, "data", "chunk", log) }
	second := func() *chunked { return newChunked(spec, "data2", "chunk2", log2) }
	capacity := int(intOf(spec["cap"]))
	limit := uintOf(spec["limit"])
	switch textOf(spec["shape"]) {
	case "plain":
		return first()
	case "bufreader":
		return rsio.BufReaderWithCapacity(capacity, first())
	case "take":
		return rsio.Take(first(), limit)
	case "take_bufreader":
		return rsio.Take(rsio.BufReaderWithCapacity(capacity, first()), limit)
	case "bufreader_take":
		return rsio.BufReaderWithCapacity(capacity, rsio.Take(first(), limit))
	case "chain":
		return rsio.Chain(first(), second())
	case "chain_bufreader":
		return rsio.Chain(rsio.BufReaderWithCapacity(capacity, first()), rsio.BufReaderWithCapacity(capacity, second()))
	case "bufreader_chain":
		return rsio.BufReaderWithCapacity(capacity, rsio.Chain(first(), second()))
	case "cursor":
		return rsio.CursorNew(decodeBytes(spec["data"]))
	case "cursor_chain":
		return rsio.Chain(rsio.CursorNew(decodeBytes(spec["data"])), rsio.CursorNew(decodeBytes(spec["data2"])))
	case "slice":
		return rsio.SliceFrom(decodeBytes(spec["data"]))
	case "empty":
		return rsio.Empty()
	case "repeat":
		return rsio.Repeat(byte(intOf(spec["byte"])))
	}
	panic("unknown reader shape " + textOf(spec["shape"]))
}

func stepArgs(step any) []any { return step.([]any) }

func readStep(reader io.Reader, step []any) (any, bool) {
	switch textOf(step[0]) {
	case "read":
		buf := make([]byte, intOf(step[1]))
		n, err := rsio.Read(reader, buf)
		if err != nil {
			return map[string]any{"err": errJSON(err)}, true
		}
		return map[string]any{"n": n, "data": show(buf[:n])}, true
	case "read_exact":
		buf := make([]byte, intOf(step[1]))
		if err := rsio.ReadExact(reader, buf); err != nil {
			return map[string]any{"err": errJSON(err)}, true
		}
		return map[string]any{"data": show(buf)}, true
	case "read_to_end":
		prefix := decodeBytes(step[1])
		buf := make([]byte, len(prefix), max(int(intOf(step[2])), len(prefix)))
		copy(buf, prefix)
		n, err := rsio.ReadToEnd(reader, &buf)
		if err != nil {
			return map[string]any{"err": errJSON(err), "data": show(buf), "cap": cap(buf)}, true
		}
		return map[string]any{"n": n, "data": show(buf), "cap": cap(buf)}, true
	case "read_to_string":
		text := textOf(step[1])
		n, err := rsio.ReadToString(reader, &text)
		if err != nil {
			return map[string]any{"err": errJSON(err), "text": text}, true
		}
		return map[string]any{"n": n, "text": text}, true
	case "bytes":
		out := []any{}
		iter := rsio.Bytes(rsio.ByRef(reader))
		for i := int64(0); i < intOf(step[1]); i++ {
			item, ok := iter.Next().Get()
			if !ok {
				break
			}
			if item.Err != nil {
				out = append(out, map[string]any{"err": errJSON(item.Err)})
			} else {
				out = append(out, item.Value)
			}
		}
		return out, true
	}
	return nil, false
}

func bufReadStep(reader rsio.BufRead, step []any) (any, bool) {
	switch textOf(step[0]) {
	case "fill_buf":
		buf, err := reader.FillBuf()
		if err != nil {
			return map[string]any{"err": errJSON(err)}, true
		}
		return map[string]any{"data": show(buf)}, true
	case "consume":
		reader.Consume(int(intOf(step[1])))
		return nil, true
	case "read_until":
		buf := decodeBytes(step[2])
		n, err := rsio.ReadUntil(reader, byte(intOf(step[1])), &buf)
		if err != nil {
			return map[string]any{"err": errJSON(err), "data": show(buf)}, true
		}
		return map[string]any{"n": n, "data": show(buf)}, true
	case "skip_until":
		n, err := rsio.SkipUntil(reader, byte(intOf(step[1])))
		if err != nil {
			return map[string]any{"err": errJSON(err)}, true
		}
		return map[string]any{"n": n}, true
	case "read_line":
		text := textOf(step[1])
		n, err := rsio.ReadLine(reader, &text)
		if err != nil {
			return map[string]any{"err": errJSON(err), "text": text}, true
		}
		return map[string]any{"n": n, "text": text}, true
	case "lines":
		out := []any{}
		iter := rsio.Lines(rsio.ByRef(reader))
		for i := int64(0); i < intOf(step[1]); i++ {
			item, ok := iter.Next().Get()
			if !ok {
				break
			}
			if item.Err != nil {
				out = append(out, map[string]any{"err": errJSON(item.Err)})
			} else {
				out = append(out, map[string]any{"line": item.Value})
			}
		}
		return out, true
	case "split":
		out := []any{}
		iter := rsio.Split(rsio.ByRef(reader), byte(intOf(step[1])))
		for i := int64(0); i < intOf(step[2]); i++ {
			item, ok := iter.Next().Get()
			if !ok {
				break
			}
			if item.Err != nil {
				out = append(out, map[string]any{"err": errJSON(item.Err)})
			} else {
				out = append(out, map[string]any{"part": show(item.Value)})
			}
		}
		return out, true
	}
	return readStep(reader, step)
}

func intsOrEmpty(values []int) []int {
	if values == nil {
		return []int{}
	}
	return values
}

func readerOp(request map[string]any) any {
	var log, log2 []int
	reader := buildReader(request, &log, &log2)
	results := []any{}
	steps, _ := request["steps"].([]any)
	for _, step := range steps {
		var (
			result any
			known  bool
		)
		if buffered, ok := reader.(rsio.BufRead); ok && isBuffered(textOf(request["shape"])) {
			result, known = bufReadStep(buffered, stepArgs(step))
		} else {
			result, known = readStep(reader, stepArgs(step))
		}
		if !known {
			panic(fmt.Sprintf("unknown reader step %v", step))
		}
		results = append(results, result)
	}
	return map[string]any{"results": results, "reads": intsOrEmpty(log), "reads2": intsOrEmpty(log2)}
}

// isBuffered says whether the oracle holds the shape as a BufRead. The
// adapters here have BufRead's methods whatever they wrap, as Go's method
// sets cannot depend on a type argument.
func isBuffered(shape string) bool {
	switch shape {
	case "plain", "take", "chain", "repeat":
		return false
	}
	return true
}

// --- writers ---------------------------------------------------------------

// recorder is the oracle's Recorder writer: it records every call, accepts
// at most max bytes a call, and can refuse from some total on or fail once
// at one. Its Write has Rust's contract: a short count is not an error.
type recorder struct {
	max    int
	zeroAt int
	errAt  int
	total  int
	log    *[]any
}

func newRecorder(spec map[string]any, log *[]any) *recorder {
	return &recorder{
		max:    int(intOf(spec["max"])),
		zeroAt: optionalInt(spec, "zero_at"),
		errAt:  optionalInt(spec, "err_at"),
		log:    log,
	}
}

func (r *recorder) Write(buf []byte) (int, error) {
	if r.errAt >= 0 && r.total >= r.errAt {
		r.errAt = -1
		*r.log = append(*r.log, map[string]any{"failed": len(buf)})
		return 0, rsio.ErrorOther("injected write failure")
	}
	if r.zeroAt >= 0 && r.total >= r.zeroAt {
		*r.log = append(*r.log, map[string]any{"refused": len(buf)})
		return 0, nil
	}
	n := len(buf)
	if r.max != 0 {
		n = min(n, r.max)
	}
	if r.errAt >= 0 {
		n = min(n, r.errAt-r.total)
	}
	if r.zeroAt >= 0 {
		n = min(n, r.zeroAt-r.total)
	}
	*r.log = append(*r.log, map[string]any{"w": show(buf[:n]), "of": len(buf)})
	r.total += n
	return n, nil
}

func (r *recorder) Flush() error {
	*r.log = append(*r.log, "flush")
	return nil
}

func writeStep(writer io.Writer, step []any) (any, bool) {
	switch textOf(step[0]) {
	case "write":
		n, err := rsio.Write(writer, decodeBytes(step[1]))
		return resultJSON(n, err), true
	case "write_all":
		return unitJSON(rsio.WriteAll(writer, decodeBytes(step[1]))), true
	case "flush":
		return unitJSON(rsio.Flush(writer)), true
	}
	return nil, false
}

func writerOp(request map[string]any) any {
	log := []any{}
	rec := newRecorder(request, &log)
	capacity := int(intOf(request["cap"]))
	steps, _ := request["steps"].([]any)
	finish := textOf(request["finish"])
	results := []any{}

	run := func(writer io.Writer, extra func(step []any) (any, bool)) {
		for _, step := range steps {
			args := stepArgs(step)
			result, known := extra(args)
			if !known {
				result, known = writeStep(writer, args)
			}
			if !known {
				panic(fmt.Sprintf("unknown writer step %v", step))
			}
			results = append(results, result)
		}
	}
	none := func([]any) (any, bool) { return nil, false }

	switch textOf(request["shape"]) {
	case "plain":
		run(rec, none)
	case "bufwriter":
		writer := rsio.BufWriterWithCapacity(capacity, rec)
		run(writer, func(step []any) (any, bool) {
			switch textOf(step[0]) {
			case "buffer":
				return show(writer.Buffer()), true
			case "capacity":
				return writer.Capacity(), true
			}
			return nil, false
		})
		log = append(log, "finish")
		if finish == "into_inner" {
			if _, err := writer.IntoInner(); err != nil {
				failure := err.(*rsio.IntoInnerError[*rsio.BufWriter[*recorder]])
				results = append(results, map[string]any{"err": errJSON(failure.IoError()), "display": failure.Error()})
				log = append(log, "drop")
				failure.IntoInner().Drop()
			} else {
				results = append(results, map[string]any{"ok": nil})
			}
		} else {
			writer.Drop()
		}
	case "linewriter":
		writer := rsio.LineWriterWithCapacity(capacity, rec)
		run(writer, none)
		log = append(log, "finish")
		if finish == "into_inner" {
			if _, err := writer.IntoInner(); err != nil {
				failure := err.(*rsio.IntoInnerError[*rsio.LineWriter[*recorder]])
				results = append(results, map[string]any{"err": errJSON(failure.IoError()), "display": failure.Error()})
				log = append(log, "drop")
				failure.IntoInner().Drop()
			} else {
				results = append(results, map[string]any{"ok": nil})
			}
		} else {
			writer.Drop()
		}
	default:
		panic("unknown writer shape")
	}
	return map[string]any{"results": results, "log": log}
}

// --- cursor ----------------------------------------------------------------

func seekFrom(step []any) rsio.SeekFrom {
	switch textOf(step[1]) {
	case "start":
		return &rsio.SeekFrom_Start{F0: uintOf(step[2])}
	case "end":
		return &rsio.SeekFrom_End{F0: intOf(step[2])}
	case "current":
		return &rsio.SeekFrom_Current{F0: intOf(step[2])}
	}
	panic("unknown seek origin")
}

func seekStep(seeker io.Seeker, step []any) (any, bool) {
	switch textOf(step[0]) {
	case "seek":
		position, err := rsio.Seek(seeker, seekFrom(step))
		return resultJSON(position, err), true
	case "rewind":
		return unitJSON(rsio.Rewind(seeker)), true
	case "stream_position":
		position, err := rsio.StreamPosition(seeker)
		return resultJSON(position, err), true
	case "seek_relative":
		return unitJSON(rsio.SeekRelative(seeker, intOf(step[1]))), true
	}
	return nil, false
}

func cursorOp(request map[string]any) any {
	init := decodeBytes(request["init"])
	var cursor *rsio.Cursor
	switch textOf(request["kind"]) {
	case "vec":
		cursor = rsio.CursorNew(init)
	case "slice":
		cursor = rsio.CursorNewSlice(init)
	default:
		panic("unknown cursor kind")
	}
	results := []any{}
	steps, _ := request["steps"].([]any)
	for _, step := range steps {
		args := stepArgs(step)
		var (
			result any
			known  = true
		)
		switch textOf(args[0]) {
		case "position":
			result = cursor.Position()
		case "set_position":
			cursor.SetPosition(uintOf(args[1]))
		case "get_ref":
			result = show(cursor.GetRef())
		default:
			if result, known = writeStep(cursor, args); !known {
				if result, known = seekStep(cursor, args); !known {
					result, known = bufReadStep(cursor, args)
				}
			}
		}
		if !known {
			panic(fmt.Sprintf("unknown cursor step %v", step))
		}
		results = append(results, result)
	}
	return map[string]any{"results": results, "position": cursor.Position(), "content": show(cursor.GetRef())}
}

// --- copy ------------------------------------------------------------------

func copyOp(request map[string]any) any {
	reader := request["reader"].(map[string]any)
	writer := request["writer"].(map[string]any)
	var reads []int
	writes := []any{}
	prefix := decodeBytes(writer["prefix"])
	sink := make([]byte, len(prefix), max(int(intOf(writer["vec_cap"])), len(prefix)))
	copy(sink, prefix)

	var source io.Reader
	switch textOf(reader["shape"]) {
	case "plain":
		source = newChunked(reader, "data", "chunk", &reads)
	case "bufreader":
		source = rsio.BufReaderWithCapacity(int(intOf(reader["cap"])), newChunked(reader, "data", "chunk", &reads))
	case "cursor":
		source = rsio.CursorNew(decodeBytes(reader["data"]))
	case "slice":
		source = rsio.SliceFrom(decodeBytes(reader["data"]))
	case "take":
		source = rsio.Take(newChunked(reader, "data", "chunk", &reads), uintOf(reader["limit"]))
	default:
		panic("unknown copy reader")
	}

	var (
		copied uint64
		err    error
	)
	switch textOf(writer["shape"]) {
	case "plain":
		copied, err = rsio.Copy(source, newRecorder(writer, &writes))
	case "bufwriter":
		target := rsio.BufWriterWithCapacity(int(intOf(writer["cap"])), newRecorder(writer, &writes))
		copied, err = rsio.Copy(source, target)
		writes = append(writes, "finish")
		target.Drop()
	case "vec":
		copied, err = rsio.Copy(source, rsio.Vec(&sink))
	default:
		panic("unknown copy writer")
	}
	return map[string]any{
		"result": resultJSON(copied, err),
		"reads":  intsOrEmpty(reads),
		"writes": writes,
		"vec":    show(sink),
	}
}

