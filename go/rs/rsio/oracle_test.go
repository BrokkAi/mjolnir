func generateIo(yield func(any)) {
	// Operating system errors: every code product code can meet, the ones
	// around the ends of the C library's table, and a few far away.
	for code := -3; code <= 200; code++ {
		yield(map[string]any{"op": "os_error", "code": code})
	}
	for _, code := range []int{255, 256, 512, 1000, 4095, 4096, 65535, 65536, 2147483647, -2147483648, -1000} {
		yield(map[string]any{"op": "os_error", "code": code})
	}
	for _, name := range stableKinds {
		yield(map[string]any{"op": "kind", "name": name})
	}
	for index, message := range errorMessages {
		kind := stableKinds[index%len(stableKinds)]
		yield(map[string]any{"op": "custom", "kind": kind, "message": message})
		yield(map[string]any{"op": "other", "message": message})
		yield(map[string]any{"op": "nested", "kind": "Other", "inner": kind, "message": message})
	}
	for index, kind := range stableKinds {
		yield(map[string]any{"op": "custom_os", "kind": kind, "code": []int{2, 13, 17, 21, 39, 0, 999}[index%7]})
		yield(map[string]any{"op": "nested", "kind": kind, "inner": stableKinds[(index*7+3)%len(stableKinds)], "message": "inner"})
	}

	random := &rng{state: 20261120}
	generateReaders(random, yield)
	generateWriters(random, yield)
	generateCursors(random, yield)
	generateCopies(random, yield)
}

