//go:build ignore

// gen_dec2flt_table writes dec2flt_table.go from the tables of the Rust
// standard library's float parser: the powers of five of
// core/src/num/imp/dec2flt/table.rs and the left-shift tables of
// decimal_seq.rs in the same directory.
//
// Run it from the repository root after go/port/fetch-reference.sh:
//
//	go run go/rs/strs/gen_dec2flt_table.go \
//	    -src ~/.cache/mjolnir/build/go-port/rust-src/src/rust/library/core/src/num/imp/dec2flt \
//	    -rust 1.99.1 -out go/rs/strs/dec2flt_table.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

func main() {
	src := flag.String("src", "", "path to core/src/num/imp/dec2flt")
	out := flag.String("out", "dec2flt_table.go", "file to write")
	rust := flag.String("rust", "", "Rust toolchain version the source belongs to")
	flag.Parse()
	if *src == "" || *rust == "" {
		flag.Usage()
		os.Exit(2)
	}
	table := read(filepath.Join(*src, "table.rs"))
	seq := read(filepath.Join(*src, "decimal_seq.rs"))

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_dec2flt_table.go from core %s src/num/imp/dec2flt/table.rs and decimal_seq.rs; DO NOT EDIT.\n\n", *rust)
	fmt.Fprintf(&b, "package strs\n\n")

	smallest := one("SMALLEST_POWER_OF_FIVE", `const SMALLEST_POWER_OF_FIVE: i32 = (-?\d+);`, table)[1]
	largest := one("LARGEST_POWER_OF_FIVE", `const LARGEST_POWER_OF_FIVE: i32 = (-?\d+);`, table)[1]
	fmt.Fprintf(&b, "const (\n\tdec2fltSmallestPowerOfFive = %s\n\tdec2fltLargestPowerOfFive = %s\n)\n\n", smallest, largest)

	body := one("POWER_OF_FIVE_128", `(?s)static POWER_OF_FIVE_128: \[\(u64, u64\); N_POWERS_OF_FIVE\] = \[\n(.*?)\n\];`, table)[1]
	pairs := regexp.MustCompile(`\((0x[0-9a-f]+), (0x[0-9a-f]+)\),\s+// 5\^(-?\d+)`).FindAllStringSubmatch(body, -1)
	low, _ := strconv.Atoi(smallest)
	high, _ := strconv.Atoi(largest)
	if len(pairs) != high-low+1 {
		fatal("POWER_OF_FIVE_128: parsed %d entries, expected %d", len(pairs), high-low+1)
	}
	fmt.Fprintf(&b, "// dec2fltPowerOfFive128 is POWER_OF_FIVE_128: for each power of five from\n// 5^%s to 5^%s, the high and the low 64 bits of its 128-bit approximation, in\n// the order Rust reads them (the pair's first element first).\n", smallest, largest)
	fmt.Fprintf(&b, "var dec2fltPowerOfFive128 = [%d][2]uint64{\n", len(pairs))
	for i, pair := range pairs {
		if power, _ := strconv.Atoi(pair[3]); power != low+i {
			fatal("POWER_OF_FIVE_128: entry %d is 5^%s, expected 5^%d", i, pair[3], low+i)
		}
		fmt.Fprintf(&b, "{%s, %s}, // 5^%s\n", pair[1], pair[2], pair[3])
	}
	fmt.Fprintf(&b, "}\n\n")

	shift := one("TABLE", `(?s)const TABLE: \[u16; (\d+)\] = \[(.*?)\];`, seq)
	emit(&b, "dec2fltLeftShiftTable", "number_of_digits_decimal_left_shift's TABLE", "uint16", shift[1], shift[2])
	pow5 := one("TABLE_POW5", `(?s)const TABLE_POW5: \[u8; (0x[0-9A-Fa-f]+)\] = \[(.*?)\];`, seq)
	emit(&b, "dec2fltLeftShiftPow5", "number_of_digits_decimal_left_shift's TABLE_POW5", "uint8", pow5[1], pow5[2])

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		fatal("generated code does not parse: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fatal("%v", err)
	}
}

func emit(b *bytes.Buffer, name, what, elem, declared, body string) {
	want, err := strconv.ParseInt(declared, 0, 64)
	if err != nil {
		fatal("%s: bad length %q", name, declared)
	}
	var items []string
	for _, item := range strings.Split(body, ",") {
		if item = strings.TrimSpace(item); item != "" {
			if _, err := strconv.ParseUint(item, 0, 64); err != nil {
				fatal("%s: %q is not a number", name, item)
			}
			items = append(items, item)
		}
	}
	if int64(len(items)) != want {
		fatal("%s: declared %d elements, parsed %d", name, want, len(items))
	}
	fmt.Fprintf(b, "// %s is %s.\nvar %s = [%d]%s{\n", name, what, name, len(items), elem)
	width := 0
	for _, item := range items {
		if width > 0 && width+len(item)+2 > 96 {
			fmt.Fprintf(b, "\n")
			width = 0
		}
		fmt.Fprintf(b, "%s, ", item)
		width += len(item) + 2
	}
	fmt.Fprintf(b, "\n}\n\n")
}

func read(path string) string {
	text, err := os.ReadFile(path)
	if err != nil {
		fatal("%v", err)
	}
	return string(text)
}

func one(what, pattern, text string) []string {
	matches := regexp.MustCompile(pattern).FindAllStringSubmatch(text, -1)
	if len(matches) != 1 {
		fatal("%s: expected one match of %q, found %d", what, pattern, len(matches))
	}
	return matches[0]
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen_dec2flt_table: "+format+"\n", args...)
	os.Exit(1)
}
