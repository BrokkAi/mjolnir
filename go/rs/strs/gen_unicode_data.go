//go:build ignore

// gen_unicode_data writes unicode_data.go from the Unicode tables of the Rust
// standard library, core/src/unicode/unicode_data.rs. The tables are copied
// as they are (skip lists, bit sets, the white-space map, the two-level case
// conversion tables); unicode.go holds the lookup code that reads them.
//
// Run it from the repository root after go/port/fetch-reference.sh, whenever
// rust-toolchain.toml moves to a toolchain with another Unicode version:
//
//	go run go/rs/strs/gen_unicode_data.go \
//	    -src ~/.cache/mjolnir/build/go-port/rust-src/src/rust/library/core/src/unicode/unicode_data.rs \
//	    -rust 1.99.1 -out go/rs/strs/unicode_data.go
//
// -package names another package, for a copy of the tables elsewhere.
//
// The generator refuses input whose shape it does not recognise: every table
// it expects must be present with the declared length, and nothing it does
// not expect may appear. The lookup code in unicode.go is a port of the
// functions of the same file; when the generator starts to fail, read the new
// unicode_data.rs and update both.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func main() {
	src := flag.String("src", "", "path to core/src/unicode/unicode_data.rs")
	out := flag.String("out", "unicode_data.go", "file to write")
	rust := flag.String("rust", "", "Rust toolchain version the source belongs to")
	pkg := flag.String("package", "strs", "Go package name")
	flag.Parse()
	if *src == "" || *rust == "" {
		flag.Usage()
		os.Exit(2)
	}
	text, err := os.ReadFile(*src)
	if err != nil {
		fatal("%v", err)
	}
	g := &generator{source: string(text)}
	g.printf("// Code generated by gen_unicode_data.go from core %s src/unicode/unicode_data.rs; DO NOT EDIT.\n\n", *rust)
	g.printf("package %s\n\n", *pkg)
	g.version()
	modules := g.modules()
	names := make([]string, 0, len(modules))
	for name := range modules {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		body := modules[name]
		switch {
		case name == "conversions":
			g.conversions(body)
		case name == "white_space":
			g.whiteSpace(body)
		case strings.Contains(body, "SHORT_OFFSET_RUNS"):
			g.skipList(name, body)
		case strings.Contains(body, "BITSET_CHUNKS_MAP"):
			g.bitSet(name, body)
		default:
			fatal("module %s: unknown table kind", name)
		}
	}
	formatted, err := format.Source(g.out.Bytes())
	if err != nil {
		fatal("generated code does not parse: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fatal("%v", err)
	}
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen_unicode_data: "+format+"\n", args...)
	os.Exit(1)
}

type generator struct {
	source string
	out    bytes.Buffer
}

func (g *generator) printf(format string, args ...any) {
	fmt.Fprintf(&g.out, format, args...)
}

// one returns the single submatch group of the single match of pattern in
// text, and fails when there is not exactly one match.
func one(what, pattern, text string) []string {
	matches := regexp.MustCompile(pattern).FindAllStringSubmatch(text, -1)
	if len(matches) != 1 {
		fatal("%s: expected one match of %q, found %d", what, pattern, len(matches))
	}
	return matches[0]
}

func number(what, text string) int64 {
	text = strings.TrimSpace(text)
	base := 10
	digits := text
	switch {
	case strings.HasPrefix(text, "0x"):
		base, digits = 16, text[2:]
	case strings.HasPrefix(text, "0b"):
		base, digits = 2, text[2:]
	}
	value, err := strconv.ParseUint(strings.ReplaceAll(digits, "_", ""), base, 64)
	if err != nil {
		signed, signedErr := strconv.ParseInt(text, 10, 64)
		if signedErr != nil {
			fatal("%s: %q is not a number", what, text)
		}
		return signed
	}
	return int64(value)
}

// list splits the body of a flat array literal into its elements.
func list(what, body string) []string {
	var items []string
	for _, item := range strings.Split(body, ",") {
		if item = strings.TrimSpace(item); item != "" {
			items = append(items, item)
		}
	}
	if len(items) == 0 {
		fatal("%s: empty table", what)
	}
	return items
}

func (g *generator) version() {
	m := one("UNICODE_VERSION", `pub const UNICODE_VERSION: \(u8, u8, u8\) = \((\d+), (\d+), (\d+)\);`, g.source)
	g.printf("// unicodeVersion is UNICODE_VERSION.\nvar unicodeVersion = [3]uint8{%s, %s, %s}\n\n", m[1], m[2], m[3])
}

// modules returns the body of every `pub mod name { .. }` at the top level.
func (g *generator) modules() map[string]string {
	header := regexp.MustCompile(`(?m)^pub mod (\w+) \{$`)
	found := map[string]string{}
	for _, loc := range header.FindAllStringSubmatchIndex(g.source, -1) {
		name := g.source[loc[2]:loc[3]]
		rest := g.source[loc[1]:]
		end := strings.Index(rest, "\n}\n")
		if end < 0 {
			fatal("module %s: no closing brace", name)
		}
		found[name] = rest[:end]
	}
	want := []string{"alphabetic", "case_ignorable", "cf", "cn_planes_0_3", "default_ignorable_code_point",
		"grapheme_extend", "lowercase", "lt", "n", "uppercase", "white_space", "conversions"}
	for _, name := range want {
		if _, ok := found[name]; !ok {
			fatal("module %s is missing", name)
		}
	}
	if len(found) != len(want) {
		fatal("found %d modules, expected %d: the file has tables this generator does not know", len(found), len(want))
	}
	return found
}

func camel(name string) string {
	parts := strings.Split(name, "_")
	for i, part := range parts {
		if i > 0 {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}
	return strings.Join(parts, "")
}

// array returns the element text of `static NAME: [T; N] = [ .. ];`, checking N.
func array(module, name, elemType, body string) []string {
	m := one(module+"::"+name, `(?s)static `+name+`: \[`+regexp.QuoteMeta(elemType)+`; (\d+)\] = \[(.*?)\n    \];`, body)
	want := int(number(module, m[1]))
	var items []string
	switch elemType {
	case "ShortOffsetRunHeader":
		for _, pair := range regexp.MustCompile(`ShortOffsetRunHeader::new\((\d+), (\d+)\)`).FindAllStringSubmatch(m[2], -1) {
			start, sum := number(module, pair[1]), number(module, pair[2])
			if start >= 1<<11 || sum >= 1<<21 {
				fatal("%s::%s: header (%d, %d) out of range", module, name, start, sum)
			}
			items = append(items, fmt.Sprintf("%d<<21 | %d", start, sum))
		}
	case "(u8, u8)":
		for _, pair := range regexp.MustCompile(`\((\d+), (\d+)\)`).FindAllStringSubmatch(m[2], -1) {
			items = append(items, fmt.Sprintf("{%s, %s}", pair[1], pair[2]))
		}
	case "[u8; 16]":
		for _, row := range regexp.MustCompile(`\[([^\[\]]*)\]`).FindAllStringSubmatch(m[2], -1) {
			cells := list(module, row[1])
			if len(cells) != 16 {
				fatal("%s::%s: a row has %d cells", module, name, len(cells))
			}
			items = append(items, "{"+strings.Join(cells, ", ")+"}")
		}
	default:
		for _, item := range list(module+"::"+name, m[2]) {
			number(module+"::"+name, item)
			items = append(items, item)
		}
	}
	if len(items) != want {
		fatal("%s::%s: declared %d elements, parsed %d", module, name, want, len(items))
	}
	return items
}

func (g *generator) table(goName, goType string, items []string) {
	g.printf("var %s = [%d]%s{\n", goName, len(items), goType)
	width := 0
	for _, item := range items {
		if width > 0 && width+len(item)+2 > 96 {
			g.printf("\n")
			width = 0
		}
		g.printf("%s, ", item)
		width += len(item) + 2
	}
	g.printf("\n}\n\n")
}

func (g *generator) skipList(name, body string) {
	min := one(name, `\(c as u32\) >= (0x[0-9a-f]+) && lookup_slow\(c\)`, body)[1]
	one(name, `(super::skip_search\(c, &SHORT_OFFSET_RUNS, &OFFSETS\))`, body)
	prefix := camel(name)
	g.printf("// %s: a skip list. %sMin is the smallest code point in it.\nconst %sMin = %s\n\n", name, prefix, prefix, min)
	g.table(prefix+"ShortOffsetRuns", "uint32", array(name, "SHORT_OFFSET_RUNS", "ShortOffsetRunHeader", body))
	g.table(prefix+"Offsets", "uint8", array(name, "OFFSETS", "u8", body))
}

func (g *generator) bitSet(name, body string) {
	min := one(name, `\(c as u32\) >= (0x[0-9a-f]+) &&\s+super::bitset_search\(`, body)[1]
	prefix := camel(name)
	g.printf("// %s: a bit set. %sMin is the smallest code point in it.\nconst %sMin = %s\n\n", name, prefix, prefix, min)
	g.table(prefix+"BitsetChunksMap", "uint8", array(name, "BITSET_CHUNKS_MAP", "u8", body))
	g.table(prefix+"BitsetIndexChunks", "[16]uint8", array(name, "BITSET_INDEX_CHUNKS", "[u8; 16]", body))
	g.table(prefix+"BitsetCanonical", "uint64", array(name, "BITSET_CANONICAL", "u64", body))
	g.table(prefix+"BitsetMapping", "[2]uint8", array(name, "BITSET_MAPPING", "(u8, u8)", body))
}

// whiteSpace copies the map and translates the `match c as u32 >> 8` of
// white_space::lookup arm by arm.
func (g *generator) whiteSpace(body string) {
	g.table("whiteSpaceMap", "uint8", array("white_space", "WHITESPACE_MAP", "u8", body))
	m := one("white_space", `(?s)match c as u32 >> 8 \{\n(.*?)\n        \}`, body)
	mapArm := regexp.MustCompile(`^(\d+) => WHITESPACE_MAP\[c as usize & 0xff\] & (\d+) != 0,$`)
	oneArm := regexp.MustCompile(`^(\d+) => c as u32 == (0x[0-9a-fA-F]+),$`)
	g.printf("// whiteSpaceLookup is white_space::lookup.\nfunc whiteSpaceLookup(c rune) bool {\n\tswitch uint32(c) >> 8 {\n")
	sawDefault := false
	for _, line := range strings.Split(m[1], "\n") {
		line = strings.TrimSpace(line)
		switch {
		case mapArm.MatchString(line):
			arm := mapArm.FindStringSubmatch(line)
			g.printf("\tcase %s:\n\t\treturn whiteSpaceMap[uint32(c)&0xff]&%s != 0\n", arm[1], arm[2])
		case oneArm.MatchString(line):
			arm := oneArm.FindStringSubmatch(line)
			g.printf("\tcase %s:\n\t\treturn uint32(c) == %s\n", arm[1], arm[2])
		case line == "_ => false,":
			sawDefault = true
			g.printf("\tdefault:\n\t\treturn false\n")
		default:
			fatal("white_space::lookup: unknown arm %q", line)
		}
	}
	if !sawDefault {
		fatal("white_space::lookup: no default arm")
	}
	g.printf("\t}\n}\n\n")
}

func (g *generator) conversions(body string) {
	// to_title and to_casefold back char::to_titlecase and
	// char::to_casefold_unnormalized, which are unstable in the toolchain this
	// was written for and so have no caller to port. Their tables are parsed,
	// to notice a change of shape, and not written.
	for _, lut := range []struct {
		rust, goName, function, ascii string
		emit                          bool
	}{
		{"LOWERCASE_LUT", "lowercaseLut", "to_lower", "to_ascii_lowercase", true},
		{"UPPERCASE_LUT", "uppercaseLut", "to_upper", "to_ascii_uppercase", true},
		{"TITLECASE_LUT", "titlecaseLut", "to_title", "to_ascii_uppercase", false},
		{"CASEFOLD_LUT", "casefoldLut", "to_casefold", "to_ascii_lowercase", false},
	} {
		written := g.out.Len()
		// The function's ASCII shortcut: `if c < '\u{C0}' { return [c.to_ascii_lowercase(), ..`.
		threshold := one(lut.function, `(?s)pub fn `+lut.function+`\(c: char\) -> \[char; 3\] \{.*?if c < '\\u\{([0-9A-Fa-f]+)\}' \{\s+return \[c\.`+lut.ascii+`\(\), '\\0', '\\0'\];`, body)[1]
		g.printf("// %sMin is the code point below which %s is the ASCII mapping.\nconst %sMin = 0x%s\n\n", camel(lut.function), lut.function, camel(lut.function), threshold)

		m := one(lut.rust, `(?s)static `+lut.rust+`: L1Lut = L1Lut \{\n        l2_luts: \[\n(.*?)\n        \],\n    \};`, body)
		planes := regexp.MustCompile(`(?s)L2Lut \{\s+singles: &\[(.*?)\n                \],\s+multis: &\[(.*?)\n                \],\s+\},`).FindAllStringSubmatch(m[1], -1)
		if len(planes) != 2 {
			fatal("%s: expected 2 planes, found %d", lut.rust, len(planes))
		}
		g.printf("// %s is conversions::%s: one table for each of planes 0 and 1.\nvar %s = [2]caseL2Lut{\n", lut.goName, lut.rust, lut.goName)
		for _, plane := range planes {
			g.printf("{\nsingles: []caseSingle{\n")
			singles := regexp.MustCompile(`\(Range::(singleton|step_by_1|step_by_2)\((0x[0-9a-f]+)(?:\.\.=(0x[0-9a-f]+))?\), (-?\d+)\)`).FindAllStringSubmatch(plane[1], -1)
			declared := one(lut.rust, `^ // (\d+) entries`, plane[1])[1]
			if int(number(lut.rust, declared)) != len(singles) {
				fatal("%s: declared %s singles, parsed %d", lut.rust, declared, len(singles))
			}
			for _, single := range singles {
				start := number(lut.rust, single[2])
				end := start
				if single[3] != "" {
					end = number(lut.rust, single[3])
				}
				if (single[1] == "singleton") != (single[3] == "") || end < start || end-start > 255 {
					fatal("%s: bad range %q", lut.rust, single[0])
				}
				delta := number(lut.rust, single[4])
				if delta < -32768 || delta > 32767 {
					fatal("%s: delta %d does not fit i16", lut.rust, delta)
				}
				g.printf("{start: %#04x, len: %d, parity: %t, delta: %d},\n", start, end-start, single[1] == "step_by_2", delta)
			}
			g.printf("},\nmultis: []caseMulti{\n")
			multis := regexp.MustCompile(`\((0x[0-9a-f]+), \[(0x[0-9a-f]+), (0x[0-9a-f]+), (0x[0-9a-f]+)\]\)`).FindAllStringSubmatch(plane[2], -1)
			declared = one(lut.rust, `^ // (\d+) entries`, plane[2])[1]
			if int(number(lut.rust, declared)) != len(multis) {
				fatal("%s: declared %s multis, parsed %d", lut.rust, declared, len(multis))
			}
			for _, multi := range multis {
				g.printf("{from: %s, to: [3]uint16{%s, %s, %s}},\n", multi[1], multi[2], multi[3], multi[4])
			}
			g.printf("},\n},\n")
		}
		g.printf("}\n\n")
		if !lut.emit {
			g.out.Truncate(written)
		}
	}
}
