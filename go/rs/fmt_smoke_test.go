package rs

import (
	"testing"
	"time"
)

func TestFmtSmoke(t *testing.T) {
	check := func(got, want string) {
		t.Helper()
		if got != want {
			t.Errorf("got %q, want %q", got, want)
		}
	}
	check(Format(""), "")
	check(Format("hello"), "hello")
	check(Format("hello {{"), "hello {")
	check(Format("{}", float32(1.0)), "1")
	check(Format("{}", 1.0), "1")
	check(Format("{}", "a"), "a")
	check(Format("{}", false), "false")
	check(Format("{}", Char('a')), "a")
	check(Format("{:?}", Char('☃')), "'☃'")
	check(Format("{:?}", "foo\nbar"), `"foo\nbar"`)
	check(Format("{:?}", "foo\x00bar\x01baz\u007fqux"), `"foo\0bar\u{1}baz\u{7f}qux"`)
	check(Format("{:o}", 10), "12")
	check(Format("{:x}", 10), "a")
	check(Format("{:X}", 10), "A")
	check(Format("{1} {0}", 0, 1), "1 0")
	check(Format("{foo} {bar}", Arg("foo", 0), Arg("bar", 1)), "0 1")
	check(Format("{foo} {1} {bar} {0}", 0, 1, Arg("foo", 2), Arg("bar", 3)), "2 1 3 0")
	check(Format("{} {0}", "a"), "a a")
	check(Format("{:4}", "a"), "a   ")
	check(Format("{:>4}", "a"), "   a")
	check(Format("{:^5}", "aa"), " aa  ")
	check(Format("{:>10.4}", "aaaaaaaaaaaaaaaaaa"), "      aaaa")
	check(Format("{:.*}", 4, "aaaaaaaaaaaaaaaaaa"), "aaaa")
	check(Format("{:.1$}", "aaaaaaaaaaaaaaaaaa", 4), "aaaa")
	check(Format("{:.a$}", "aaaaaaaaaaaaaaaaaa", Arg("a", 4)), "aaaa")
	check(Format("{:1$}", "a", 4), "a   ")
	check(Format("{1:0$}", 4, "a"), "a   ")
	check(Format("{:/^10.8}", "1234567890"), "/12345678/")
	check(Format("{:.3}", 1.0), "1.000")
	check(Format("{:10.3}", 1.0), "     1.000")
	check(Format("{:+10.3}", 1.0), "    +1.000")
	check(Format("{:e}", 1.2345e6), "1.2345e6")
	check(Format("{:E}", 1.2345e6), "1.2345E6")
	check(Format("{:.3e}", 1.2345e6), "1.234e6")
	check(Format("{:+10.3e}", -1.2345e6), "  -1.234e6")
	check(Format("{}", -0.0), "0")
	check(Format("{:?}", 0.0), "0.0")
	check(Format("{:03}", 1), "001")
	check(Format("{:<+03}", 1), "+01")
	check(Format("{:#05x}", 1), "0x001")
	check(Format("{:^05}", -1.2), "-01.2")
	check(Format("{:x}{0:X}{a:x}{:X}{1:x}{a:X}", 13, 14, Arg("a", 15)), "dDfEeF")
	check(Format("{a:.*} {0} {:.*}", 4, 3, "efgh", Arg("a", "abcdef")), "abcd 4 efg")
	check(Format("{:.a$} {a} {a:#x}", "aaaaaa", Arg("a", 2)), "aa 2 0x2")
	check(Format("{:?}", Some(1)), "Some(1)")
	check(Format("{:?}", None[int]()), "None")
	check(Format("{:?}", []string{"a", "b"}), `["a", "b"]`)
	check(Format("{:#?}", []string{"a", "b"}), "[\n    \"a\",\n    \"b\",\n]")
	check(Format("{:?}", map[string]int{"b": 2, "a": 1}), `{"a": 1, "b": 2}`)
	check(Format("{:?}", T2(1, "x")), `(1, "x")`)
	check(Format("{:?}", Unit{}), "()")
	check(Format("{:?}", 1500*time.Millisecond), "1.5s")
	check(Format("{:?}", 3*time.Microsecond), "3µs")
	check(Format("{:?}", 0.1), "0.1")
	check(Format("{:?}", 1e16), "1e16")
	check(Format("{:?}", 1e-5), "1e-5")
	check(Format("{}", 1e16), "10000000000000000")
	check(Format("{}", float32(0.1)), "0.1")
	check(Format("{}", 0.3), "0.3")
	check(Format("{}", 1.0/3.0), "0.3333333333333333")
	check(Format("{:5?}", Some(1)), "Some(    1)")
}
