//go:build ignore

// gen.go writes the files of this package that are data carried over from the
// unicode-width crate, so that they are the crate's own tables and not some
// other Unicode version's:
//
//	tables_data.go                   the lookup tables of src/tables.rs
//	testdata/normalization_test.txt  NORMALIZATION_TEST of src/tables.rs
//	testdata/emoji-test.txt          tests/emoji-test.txt, copied
//
// Run it from this directory with `go generate` (or `go run gen.go [crate
// directory]`). Without an argument it reads the crate from the Cargo
// registry, where go/port/fetch-reference.sh puts it.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const crateName = "unicode-width-0.2.2"

func main() {
	crate := crateDirectory()
	source := string(read(filepath.Join(crate, "src", "tables.rs")))

	writeTables(source)
	writeNormalizationTest(source)
	write(filepath.Join("testdata", "emoji-test.txt"), read(filepath.Join(crate, "tests", "emoji-test.txt")))
}

func crateDirectory() string {
	if len(os.Args) > 1 {
		return os.Args[1]
	}
	home, err := os.UserHomeDir()
	check(err)
	matches, err := filepath.Glob(filepath.Join(home, ".cargo", "registry", "src", "*", crateName))
	check(err)
	if len(matches) == 0 {
		fail("%s is not in the Cargo registry; run go/port/fetch-reference.sh", crateName)
	}
	return matches[0]
}

// A node is one value of a Rust table initializer: a number, or an array or
// tuple of values.
type node struct {
	leaf  bool
	value uint64
	kids  []*node
}

// table describes one static of tables.rs and the Go variable it becomes.
type table struct {
	rust   string // name of the static
	goName string
	doc    string
	// shape is the Go type, outermost first: "[256]uint8",
	// "[20][64]uint8", "ranges3" for [([u8; 3], [u8; 3]); N], "pairs" for
	// [(u8, u8); N].
	shape string
	dims  []int
}

func writeTables(source string) {
	tables := []table{
		{rust: "WIDTH_ROOT", goName: "tablesWidthRoot", shape: "bytes", dims: []int{256},
			doc: "Autogenerated. 1 sub-table(s). Consult [tablesLookupWidth] for layout info.)"},
		{rust: "WIDTH_ROOT_CJK", goName: "tablesWidthRootCjk", shape: "bytes", dims: []int{256},
			doc: "Autogenerated. 16 sub-table(s). Consult [tablesLookupWidth] for layout info.)"},
		{rust: "WIDTH_MIDDLE", goName: "tablesWidthMiddle", shape: "bytes", dims: []int{20, 64},
			doc: "Autogenerated. 4 sub-table(s). Consult [tablesLookupWidth] for layout info."},
		{rust: "WIDTH_LEAVES", goName: "tablesWidthLeaves", shape: "bytes", dims: []int{186, 32},
			doc: "Autogenerated. 186 sub-table(s). Consult [tablesLookupWidth] for layout info."},
		{rust: "NON_TRANSPARENT_ZERO_WIDTHS", goName: "tablesNonTransparentZeroWidths", shape: "ranges3", dims: []int{71},
			doc: "Sorted list of codepoint ranges (inclusive)\nthat are zero-width but not `Joining_Type=Transparent`\nFIXME: can we get better compression?"},
		{rust: "SOLIDUS_TRANSPARENT", goName: "tablesSolidusTransparent", shape: "ranges3", dims: []int{208},
			doc: "Sorted list of codepoint ranges (inclusive)\nthat don't affect how the combining solidus applies\n(mostly ccc > 1).\nFIXME: can we get better compression?"},
		{rust: "EMOJI_PRESENTATION_LEAVES", goName: "tablesEmojiPresentationLeaves", shape: "bytes", dims: []int{7, 128},
			doc: "Array of 1024-bit bitmaps. Index into the correct bitmap with the 10 LSB of your codepoint\nto get whether it can start an emoji presentation sequence."},
	}
	textLeaves := []int{4, 1, 15, 10, 3, 1, 13, 22, 4, 10}
	for index, length := range textLeaves {
		tables = append(tables, table{
			rust:   "TEXT_PRESENTATION_LEAF_" + strconv.Itoa(index),
			goName: "tablesTextPresentationLeaf" + strconv.Itoa(index),
			shape:  "pairs", dims: []int{length},
		})
	}
	modifierLeaves := []int{2, 1, 4, 9, 4, 6, 12, 2}
	for index, length := range modifierLeaves {
		tables = append(tables, table{
			rust:   "EMOJI_MODIFIER_LEAF_" + strconv.Itoa(index),
			goName: "tablesEmojiModifierLeaf" + strconv.Itoa(index),
			shape:  "pairs", dims: []int{length},
		})
	}

	var out bytes.Buffer
	out.WriteString("// Port of unicode-width 0.2.2 src/tables.rs\n")
	out.WriteString("// Code generated by gen.go from the crate's src/tables.rs; DO NOT EDIT.\n\n")
	out.WriteString("// This file holds the lookup tables of src/tables.rs, with the entries that\n")
	out.WriteString("// the crate compiles under its `cjk` feature included. The functions that read\n")
	out.WriteString("// them are in tables.go.\n\n")
	out.WriteString("package unicodewidth\n\n")
	out.WriteString("import \"github.com/BrokkAi/mjolnir/go/rs\"\n\n")
	for _, t := range tables {
		value := parseStatic(source, t.rust)
		for _, line := range strings.Split(t.doc, "\n") {
			if line != "" {
				out.WriteString("// " + line + "\n")
			}
		}
		switch t.shape {
		case "bytes":
			out.WriteString("var " + t.goName + " = " + byteArrayType(t.dims) + "{\n")
			emitBytes(&out, value, t.dims, t.rust)
			out.WriteString("}\n\n")
		case "ranges3":
			expectLen(value, t.dims[0], t.rust)
			fmt.Fprintf(&out, "var %s = [%d]rs.Tuple2[[3]uint8, [3]uint8]{\n", t.goName, t.dims[0])
			for _, pair := range value.kids {
				expectLen(pair, 2, t.rust)
				fmt.Fprintf(&out, "{F0: [3]uint8{%s}, F1: [3]uint8{%s}},\n",
					hexList(pair.kids[0], 3, t.rust), hexList(pair.kids[1], 3, t.rust))
			}
			out.WriteString("}\n\n")
		case "pairs":
			expectLen(value, t.dims[0], t.rust)
			fmt.Fprintf(&out, "var %s = [%d]rs.Tuple2[uint8, uint8]{\n", t.goName, t.dims[0])
			for _, pair := range value.kids {
				fmt.Fprintf(&out, "{%s},\n", keyed(pair, 2, t.rust))
			}
			out.WriteString("}\n\n")
		}
	}
	formatted, err := format.Source(out.Bytes())
	check(err)
	write("tables_data.go", formatted)
}

func byteArrayType(dims []int) string {
	var b strings.Builder
	for _, dim := range dims {
		fmt.Fprintf(&b, "[%d]", dim)
	}
	return b.String() + "uint8"
}

func emitBytes(out *bytes.Buffer, value *node, dims []int, name string) {
	expectLen(value, dims[0], name)
	if len(dims) == 1 {
		for index, kid := range value.kids {
			if !kid.leaf || kid.value > 0xFF {
				fail("%s: entry %d is not a byte", name, index)
			}
			fmt.Fprintf(out, "0x%02X,", kid.value)
			if index%16 == 15 {
				out.WriteByte('\n')
			} else {
				out.WriteByte(' ')
			}
		}
		out.WriteByte('\n')
		return
	}
	for _, kid := range value.kids {
		out.WriteString("{\n")
		emitBytes(out, kid, dims[1:], name)
		out.WriteString("},\n")
	}
}

func hexList(value *node, length int, name string) string {
	expectLen(value, length, name)
	parts := make([]string, length)
	for index, kid := range value.kids {
		if !kid.leaf || kid.value > 0xFF {
			fail("%s: not a byte", name)
		}
		parts[index] = fmt.Sprintf("0x%02X", kid.value)
	}
	return strings.Join(parts, ", ")
}

func keyed(value *node, length int, name string) string {
	expectLen(value, length, name)
	parts := make([]string, length)
	for index, kid := range value.kids {
		if !kid.leaf || kid.value > 0xFF {
			fail("%s: not a byte", name)
		}
		parts[index] = fmt.Sprintf("F%d: 0x%02X", index, kid.value)
	}
	return strings.Join(parts, ", ")
}

func expectLen(value *node, length int, name string) {
	if value.leaf || len(value.kids) != length {
		fail("%s: expected %d entries, found %d", name, length, len(value.kids))
	}
}

// parseStatic returns the value of `static <name>: <type> = <value>;`.
func parseStatic(source, name string) *node {
	marker := "static " + name + ": "
	start := strings.Index(source, marker)
	if start < 0 || strings.Count(source, marker) != 1 {
		fail("static %s: found %d times", name, strings.Count(source, marker))
	}
	rest := source[start+len(marker):]
	equals := strings.Index(rest, " = ")
	if equals < 0 {
		fail("static %s has no initializer", name)
	}
	parser := &parser{text: rest[equals+3:], name: name}
	value := parser.value()
	parser.space()
	if !strings.HasPrefix(parser.text[parser.pos:], ";") {
		fail("static %s: initializer does not end in `;`", name)
	}
	return value
}

type parser struct {
	text string
	pos  int
	name string
}

func (p *parser) space() {
	for p.pos < len(p.text) {
		switch {
		case strings.ContainsRune(" \t\r\n", rune(p.text[p.pos])):
			p.pos++
		case strings.HasPrefix(p.text[p.pos:], "//"):
			end := strings.IndexByte(p.text[p.pos:], '\n')
			if end < 0 {
				fail("static %s: unterminated comment", p.name)
			}
			p.pos += end
		default:
			return
		}
	}
}

func (p *parser) value() *node {
	p.space()
	if p.pos >= len(p.text) {
		fail("static %s: unexpected end of file", p.name)
	}
	c := p.text[p.pos]
	switch {
	case c == '[' || c == '(':
		closing := byte(']')
		if c == '(' {
			closing = ')'
		}
		p.pos++
		list := &node{}
		for {
			p.space()
			// The entries under `#[cfg(feature = "cjk")]` are part of the
			// build this package reproduces (the feature is on by default and
			// Mjolnir leaves it on); any other attribute is unexpected.
			for strings.HasPrefix(p.text[p.pos:], "#[") {
				const cjk = `#[cfg(feature = "cjk")]`
				if !strings.HasPrefix(p.text[p.pos:], cjk) {
					fail("static %s: unexpected attribute at %q", p.name, p.text[p.pos:p.pos+40])
				}
				p.pos += len(cjk)
				p.space()
			}
			if p.text[p.pos] == closing {
				p.pos++
				return list
			}
			list.kids = append(list.kids, p.value())
			p.space()
			if p.text[p.pos] == ',' {
				p.pos++
			}
		}
	case c >= '0' && c <= '9':
		end := p.pos
		for end < len(p.text) && (isAlnum(p.text[end]) || p.text[end] == '_') {
			end++
		}
		number, err := strconv.ParseUint(strings.ReplaceAll(p.text[p.pos:end], "_", ""), 0, 64)
		if err != nil {
			fail("static %s: %v", p.name, err)
		}
		p.pos = end
		return &node{leaf: true, value: number}
	case isAlnum(c):
		// A wrapper such as Align128(...): the alignment is a detail of the
		// Rust build, the value is what is inside.
		end := p.pos
		for end < len(p.text) && isAlnum(p.text[end]) {
			end++
		}
		if end >= len(p.text) || p.text[end] != '(' {
			fail("static %s: unexpected identifier %q", p.name, p.text[p.pos:end])
		}
		p.pos = end + 1
		inner := p.value()
		p.space()
		if p.text[p.pos] != ')' {
			fail("static %s: wrapper is not closed", p.name)
		}
		p.pos++
		return inner
	}
	fail("static %s: unexpected %q", p.name, c)
	return nil
}

func isAlnum(c byte) bool {
	return c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
}

// writeNormalizationTest writes the test table of src/tables.rs in the form of
// the Unicode file it was made from (NormalizationTest.txt): five columns of
// code points in hexadecimal, each column ended by a semicolon.
func writeNormalizationTest(source string) {
	marker := "static NORMALIZATION_TEST: [(&str, &str, &str, &str, &str); 20034] = ["
	start := strings.Index(source, marker)
	if start < 0 {
		fail("NORMALIZATION_TEST not found")
	}
	body := source[start+len(marker):]
	end := strings.Index(body, "\n    ];")
	if end < 0 {
		fail("NORMALIZATION_TEST is not closed")
	}
	body = body[:end]
	column := regexp.MustCompile(`r#"(.*?)"#`)
	var out bytes.Buffer
	out.WriteString("# NORMALIZATION_TEST of unicode-width 0.2.2 src/tables.rs, written by gen.go.\n")
	out.WriteString("# Each line is one entry: the source string and its NFC, NFD, NFKC and NFKD\n")
	out.WriteString("# forms, as code points in hexadecimal, in the layout of the Unicode 17.0.0\n")
	out.WriteString("# NormalizationTest.txt the crate took them from.\n")
	rows := 0
	for _, line := range strings.Split(body, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		columns := column.FindAllStringSubmatch(line, -1)
		if len(columns) != 5 || !strings.HasPrefix(line, "(") || !strings.HasSuffix(line, "),") {
			fail("NORMALIZATION_TEST: unexpected line %q", line)
		}
		for _, match := range columns {
			for index, r := range match[1] {
				if index > 0 {
					out.WriteByte(' ')
				}
				fmt.Fprintf(&out, "%04X", r)
			}
			out.WriteByte(';')
		}
		out.WriteByte('\n')
		rows++
	}
	if rows != 20034 {
		fail("NORMALIZATION_TEST: %d rows, expected 20034", rows)
	}
	write(filepath.Join("testdata", "normalization_test.txt"), out.Bytes())
}

func read(path string) []byte {
	data, err := os.ReadFile(path)
	check(err)
	return data
}

func write(path string, data []byte) {
	check(os.MkdirAll(filepath.Dir(path), 0o755))
	check(os.WriteFile(path, data, 0o644))
	fmt.Printf("wrote %s (%d bytes)\n", path, len(data))
}

func check(err error) {
	if err != nil {
		fail("%v", err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen: "+format+"\n", args...)
	os.Exit(1)
}
