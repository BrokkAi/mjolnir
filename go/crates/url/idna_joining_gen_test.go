// joiningProbeChunk is how many scalar values one joining_probe request
// covers.
const joiningProbeChunk = 0x1000

// joiningProbeBases are the dual-joining characters the probes put next to
// ZERO WIDTH NON-JOINER: one left-to-right (MONGOLIAN LETTER A) and one
// right-to-left (ARABIC LETTER BEH), so that the Bidi rule does not reject a
// probe for the direction of the character being asked about.
var joiningProbeBases = []rune{'ᠠ', 'ب'}

// expandRunLengths undoes the oracle's run_lengths: "0*4 7*3 " is "0000777".
func expandRunLengths(t testing.TB, encoded string) string {
	var out strings.Builder
	for _, run := range strings.Fields(encoded) {
		class, count, ok := strings.Cut(run, "*")
		n, err := strconv.Atoi(count)
		if !ok || err != nil {
			t.Fatalf("bad run %q", run)
		}
		out.WriteString(strings.Repeat(class, n))
	}
	return out.String()
}

func runLengths(classes string) string {
	var out strings.Builder
	for i := 0; i < len(classes); {
		j := i
		for j < len(classes) && classes[j] == classes[i] {
			j++
		}
		fmt.Fprintf(&out, "%c*%d ", classes[i], j-i)
		i = j
	}
	return out.String()
}

// TestGenerateJoiningTable writes idna_joining_table.go. It asks the Rust
// implementation, through the oracle, which characters may stand on either
// side of a ZERO WIDTH NON-JOINER and which are skipped there, and that is
// the Joining_Type as far as the ContextJ rule reads it. No Go library has
// the property, and the system's Unicode data need not be the version the
// crate's ICU4X data is.
//
// Run it with:
//
//	MJ_URL_GENERATE=1 go/port/gotest.sh ./go/crates/url/ -run TestGenerateJoiningTable
func TestGenerateJoiningTable(t *testing.T) {
	if os.Getenv("MJ_URL_GENERATE") == "" {
		t.Skip("set MJ_URL_GENERATE=1 to regenerate idna_joining_table.go from the Rust oracle")
	}
	directory := filepath.Join(oracle.RepoRoot(t), "go", "port", "oracle")
	build := exec.Command("cargo", "build", "--release", "--quiet", "--features", "url", "--target-dir", filepath.Join("target", "url"))
	build.Dir = directory
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build oracle: %v\n%s", err, output)
	}
	var requests bytes.Buffer
	for start := 0; start < 0x110000; start += joiningProbeChunk {
		fmt.Fprintf(&requests, "{\"op\":\"joining_probe\",\"start\":%d,\"end\":%d}\n", start, start+joiningProbeChunk)
	}
	run := exec.Command(filepath.Join(directory, "target", "url", "release", "oracle"), "url")
	run.Stdin = &requests
	run.Stderr = os.Stderr
	output, err := run.Output()
	if err != nil {
		t.Fatalf("run oracle: %v", err)
	}

	var ranges []idnaJoiningRange
	code := uint32(0)
	scanner := bufio.NewScanner(bytes.NewReader(output))
	scanner.Buffer(make([]byte, 1<<20), 1<<24)
	for scanner.Scan() {
		var reply struct {
			Classes string `json:"classes"`
		}
		if err := json.Unmarshal(scanner.Bytes(), &reply); err != nil {
			t.Fatal(err)
		}
		for _, class := range expandRunLengths(t, reply.Classes) {
			jt := idnaJoiningType_Other
			// Only a character that may appear in a label is ever looked
			// up; for any other the probe saw what it maps to.
			if class != '-' && idnaAdapterIsValid(rune(code)) {
				bits := class - '0'
				switch {
				case bits&1 != 0 && bits&2 != 0:
					jt = idnaJoiningType_DualJoining
				case bits&1 != 0:
					jt = idnaJoiningType_LeftJoining
				case bits&2 != 0:
					jt = idnaJoiningType_RightJoining
				case bits&4 != 0:
					jt = idnaJoiningType_Transparent
				}
			}
			if jt != idnaJoiningType_Other {
				if n := len(ranges); n > 0 && ranges[n-1].hi+1 == code && ranges[n-1].jt == jt {
					ranges[n-1].hi = code
				} else {
					ranges = append(ranges, idnaJoiningRange{lo: code, hi: code, jt: jt})
				}
			}
			code++
		}
	}
	if code != 0x110000 {
		t.Fatalf("the oracle answered for %#x scalar values, want 0x110000", code)
	}

	names := map[idnaJoiningType]string{
		idnaJoiningType_LeftJoining:  "idnaJoiningType_LeftJoining",
		idnaJoiningType_RightJoining: "idnaJoiningType_RightJoining",
		idnaJoiningType_DualJoining:  "idnaJoiningType_DualJoining",
		idnaJoiningType_Transparent:  "idnaJoiningType_Transparent",
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by TestGenerateJoiningTable; DO NOT EDIT.\n\n")
	out.WriteString("package url\n\n")
	out.WriteString("// idnaJoiningTable holds the Joining_Type of every character whose UTS 46\n")
	out.WriteString("// status is valid or deviation and whose type is Left_Joining,\n")
	out.WriteString("// Right_Joining, Dual_Joining or Transparent, as the idna crate 1.1.0 with\n")
	out.WriteString("// idna_adapter 1.2.2 (ICU4X 2.2.0 data, Unicode 17.0) reads it. The ranges are\n")
	out.WriteString("// in order.\n")
	out.WriteString("var idnaJoiningTable = []idnaJoiningRange{\n")
	for _, r := range ranges {
		fmt.Fprintf(&out, "\t{0x%04X, 0x%04X, %s},\n", r.lo, r.hi, names[r.jt])
	}
	out.WriteString("}\n")
	if err := os.WriteFile("idna_joining_table.go", out.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %d ranges", len(ranges))
}
