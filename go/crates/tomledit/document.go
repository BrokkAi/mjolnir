// Port of toml_edit 0.20.2 src/document.rs

package tomledit

import (
	"iter"

	"github.com/BrokkAi/mjolnir/go/rs"
)

// Document is toml_edit::Document: type representing a TOML document.
type Document struct {
	root Item
	// Trailing comments and whitespaces
	trailing RawString
	original rs.Option[string]
	span     rs.Option[Range]
}

// DocumentNew is Document::new: creates an empty document.
func DocumentNew() Document {
	return DocumentDefault()
}

// AsItem is Document::as_item: returns a reference to the root item.
func (d *Document) AsItem() Item {
	return d.root
}

// AsItemMut is Document::as_item_mut: returns a mutable reference to the
// root item.
func (d *Document) AsItemMut() *Item {
	return &d.root
}

// AsTable is Document::as_table: returns a reference to the root table.
func (d *Document) AsTable() *Table {
	return d.root.AsTable().Expect("root should always be a table")
}

// AsTableMut is Document::as_table_mut: returns a mutable reference to the
// root table.
func (d *Document) AsTableMut() *Table {
	return d.root.AsTableMut().Expect("root should always be a table")
}

// Iter is Document::iter: returns an iterator over the root table.
func (d *Document) Iter() iter.Seq2[string, Item] {
	return d.AsTable().Iter()
}

// SetTrailing is Document::set_trailing: set whitespace after last element
// (a string or a RawString).
func (d *Document) SetTrailing(trailing any) {
	d.trailing = intoRawString(trailing)
}

// Trailing is Document::trailing: whitespace after last element.
func (d *Document) Trailing() *RawString {
	return &d.trailing
}

// # Panics
//
// If run on on a `Document` not generated by the parser
func (d *Document) despan() {
	d.span = rs.None[Range]()
	original := d.original.Unwrap()
	d.root.despan(original)
	d.trailing.despan(original)
}

// DocumentDefault is `impl Default for Document`.
func DocumentDefault() Document {
	return Document{
		root:     &Item_Table{F0: tableWithPos(rs.Some(0))},
		trailing: RawStringDefault(),
		original: rs.None[string](),
		span:     rs.None[Range](),
	}
}

// DocumentFromStr is `impl FromStr for Document`: parses a document from a
// &str.
func DocumentFromStr(s string) (Document, error) {
	d, err := parseDocument(s)
	if err != nil {
		return Document{}, err
	}
	d.despan()
	return d, nil
}

// Deref is `impl Deref<Target = Table> for Document` (and DerefMut): the
// root table, whose methods Rust code calls on the document itself.
func (d *Document) Deref() *Table {
	return d.AsTableMut()
}

// DocumentFromTable is `impl From<Table> for Document`.
func DocumentFromTable(root Table) Document {
	document := DocumentDefault()
	document.root = &Item_Table{F0: root}
	return document
}

// Clone is the derived `Clone for Document`.
func (d *Document) Clone() Document {
	cloned := *d
	cloned.root = d.root.Clone()
	return cloned
}

// FmtDebug is the derived `Debug for Document`.
func (d *Document) FmtDebug(f *rs.Formatter) error {
	return f.DebugStruct("Document").Field("root", d.root).Field("trailing", d.trailing).
		Field("original", d.original).Field("span", d.span).Finish()
}
