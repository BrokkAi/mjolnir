// qrAssertEq is `assert_eq!` for values Go compares as Rust does.
func qrAssertEq[T comparable](t *testing.T, left T, right T) {
	t.Helper()
	if left != right {
		t.Fatalf("assertion `left == right` failed\n  left: %s\n right: %s", rs.DebugString(left), rs.DebugString(right))
	}
}

// qrAssertSliceEq is `assert_eq!` on two vectors.
func qrAssertSliceEq[T comparable](t *testing.T, left []T, right []T) {
	t.Helper()
	if !slices.Equal(left, right) {
		t.Fatalf("assertion `left == right` failed\n  left: %v\n right: %v", left, right)
	}
}

// qrAssert is `assert!`.
func qrAssert(t *testing.T, cond bool) {
	t.Helper()
	if !cond {
		t.Fatal("assertion failed")
	}
}

// qrAssertModule is `assert_eq!` on two modules.
func qrAssertModule(t *testing.T, left CanvasModule, right CanvasModule) {
	t.Helper()
	if !left.Equal(right) {
		t.Fatalf("assertion `left == right` failed\n  left: %s\n right: %s", rs.DebugString(left), rs.DebugString(right))
	}
}

// toDebugStr is Canvas::to_debug_str (`#[cfg(test)]`): converts the canvas
// into a human-readable string.
func (c *CanvasCanvas) toDebugStr() string {
	width := c.width
	var res strings.Builder
	for y := int16(0); y < width; y++ {
		res.WriteByte('\n')
		for x := int16(0); x < width; x++ {
			switch m := c.Get(x, y).(type) {
			case *CanvasModule_Empty:
				res.WriteByte('?')
			case *CanvasModule_Masked:
				res.WriteByte(ColorSelect[byte](m.F0, '#', '.'))
			case *CanvasModule_Unmasked:
				res.WriteByte(ColorSelect[byte](m.F0, '*', '-'))
			default:
				panic(rs.Unreachable(m))
			}
		}
	}
	return res.String()
}

// canvasDataModuleIterCollect is `.collect::<Vec<(i16, i16)>>()`.
func canvasDataModuleIterCollect(it *canvasDataModuleIter) []canvasCoord {
	var coords []canvasCoord
	for {
		x, y, ok := it.next()
		if !ok {
			return coords
		}
		coords = append(coords, canvasCoord{x, y})
	}
}

