//{{{ QR code error correction

// EcConstructCodewords is ec::construct_codewords: constructs data and error
// correction codewords ready to be put in the QR code matrix.
//
// # Errors
//
// Returns `Err(QrError::InvalidVersion)` if it is not valid to use the
// `ecLevel` for the given version (e.g. `Version::Micro(1)` with
// `EcLevel::H`).
func EcConstructCodewords(rawbits []byte, version Version, ecLevel EcLevel) ([]byte, []byte, error) {
	perBlock, err := VersionFetch(version, ecLevel, ecDataBytesPerBlock[:])
	if err != nil {
		return nil, nil, err
	}
	block1Size, block1Count, block2Size, block2Count := perBlock[0], perBlock[1], perBlock[2], perBlock[3]

	blocksCount := block1Count + block2Count
	block1End := block1Size * block1Count
	totalSize := block1End + block2Size*block2Count

	if debugAssertions && len(rawbits) != totalSize {
		rs.PanicAt(1, "assertion `left == right` failed\n  left: "+strconv.Itoa(len(rawbits))+"\n right: "+strconv.Itoa(totalSize))
	}

	// Divide the data into blocks.
	blocks := make([][]byte, 0, blocksCount)
	blocks = append(blocks, ecChunks(bitsSlice(rawbits, 0, block1End), block1Size)...)
	if block2Size > 0 {
		blocks = append(blocks, ecChunks(rawbits[block1End:], block2Size)...)
	}

	// Generate EC codes.
	ecBytes, err := VersionFetch(version, ecLevel, ecEcBytesPerBlock[:])
	if err != nil {
		return nil, nil, err
	}
	ecCodes := make([][]byte, 0, len(blocks))
	for _, block := range blocks {
		ecCodes = append(ecCodes, EcCreateErrorCorrectionCode(block, ecBytes))
	}

	blocksVec := ecInterleave(blocks)
	ecVec := ecInterleave(ecCodes)

	return blocksVec, ecVec, nil
}

// ecChunks is `data.chunks(size)`.
func ecChunks(data []byte, size int) [][]byte {
	if size == 0 {
		rs.PanicAt(2, "chunk size must be non-zero")
	}
	var chunks [][]byte
	for len(data) > 0 {
		n := min(size, len(data))
		chunks = append(chunks, data[:n])
		data = data[n:]
	}
	return chunks
}

