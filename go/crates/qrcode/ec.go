//{{{ Interleave support

// ecInterleave is interleave: this method interleaves a vector of slices into
// a single vector.
//
// It will first insert all the first elements of the slices in `blocks`,
// then all the second elements, then all the third elements, and so on.
//
// The longest slice must be at the last of `blocks`, and `blocks` must not be
// empty.
func ecInterleave(blocks [][]byte) []byte {
	if len(blocks) == 0 {
		rs.PanicAt(1, "non-empty blocks")
	}
	lastBlockLen := len(blocks[len(blocks)-1])
	res := make([]byte, 0, lastBlockLen*len(blocks))
	for i := range lastBlockLen {
		for _, t := range blocks {
			if i < len(t) {
				res = append(res, t[i])
			}
		}
	}
	return res
}

//}}}
