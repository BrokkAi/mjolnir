//{{{ Number of allowed errors

// EcMaxAllowedErrors is ec::max_allowed_errors: computes the maximum allowed
// number of erratic modules can be introduced to the QR code, before the
// data becomes truly corrupted.
//
// # Errors
//
// Returns `Err(QrError::InvalidVersion)` if it is not valid to use the
// `ecLevel` for the given version (e.g. `Version::Micro(1)` with
// `EcLevel::H`).
func EcMaxAllowedErrors(version Version, ecLevel EcLevel) (int, error) {
	micro, isMicro := version.(*Version_Micro)
	normal, isNormal := version.(*Version_Normal)
	isMicroN := func(n int16) bool { return isMicro && micro.F0 == n }
	isNormalN := func(n int16) bool { return isNormal && normal.F0 == n }

	var p int
	switch {
	case (isMicroN(2) || isNormalN(1)) && ecLevel == EcLevel_L:
		p = 3
	case ((isMicro || isNormalN(2)) && ecLevel == EcLevel_L) || ((isMicroN(2) || isNormalN(1)) && ecLevel == EcLevel_M):
		p = 2
	case isNormalN(1) || (isNormalN(3) && ecLevel == EcLevel_L):
		p = 1
	default:
		p = 0
	}

	ecBytesPerBlock, err := VersionFetch(version, ecLevel, ecEcBytesPerBlock[:])
	if err != nil {
		return 0, err
	}
	perBlock, err := VersionFetch(version, ecLevel, ecDataBytesPerBlock[:])
	if err != nil {
		return 0, err
	}
	count1, count2 := perBlock[1], perBlock[3]
	ecBytes := (count1 + count2) * ecBytesPerBlock

	if debugAssertions && p > ecBytes {
		rs.PanicAt(1, panicSubOverflow)
	}
	return (ecBytes - p) / 2, nil
}

