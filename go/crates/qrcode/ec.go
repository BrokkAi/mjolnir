//{{{ Error correction primitive

// EcCreateErrorCorrectionCode is ec::create_error_correction_code: creates
// the error correction code in N bytes.
//
// This method only supports computing the error-correction code up to 69
// bytes. Longer blocks will result in task panic.
//
// This method treats the data as a polynomial of the form
// (a[0] x^(m+n) + a[1] x^(m+n-1) + … + a[m] x^n) in GF(2^8), and then
// computes the polynomial modulus with a generator polynomial of degree N.
func EcCreateErrorCorrectionCode(data []byte, ecCodeSize int) []byte {
	dataLen := len(data)
	if ecCodeSize >= len(ecGeneratorPolynomials) {
		rs.PanicAt(1, "index out of bounds: the len is "+strconv.Itoa(len(ecGeneratorPolynomials))+" but the index is "+strconv.Itoa(ecCodeSize))
	}
	logDen := ecGeneratorPolynomials[ecCodeSize]

	res := make([]byte, ecCodeSize+dataLen)
	copy(res, data)

	// rust-lang-nursery/rust-clippy#2213
	for i := range dataLen {
		leadCoeff := int(res[i])
		if leadCoeff == 0 {
			continue
		}

		logLeadCoeff := int(ecLogTable[leadCoeff])
		rest := res[i+1:]
		for k := 0; k < len(rest) && k < len(logDen); k++ {
			rest[k] ^= ecExpTable[(int(logDen[k])+logLeadCoeff)%255]
		}
	}

	return res[dataLen:]
}

