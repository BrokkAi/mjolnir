//go:build ignore

// gen.go writes the files of this package that are data carried over from the
// unicode-segmentation crate, so that they are the crate's own tables and not
// some other Unicode version's:
//
//	tables_data.go         the property tables of src/tables.rs
//	it_testdata_test.go    the conformance cases of tests/testdata/mod.rs
//
// The sentence tables and the sentence test cases are left out, as sentence
// boundaries are (see doc.go).
//
// Run it from this directory with `go generate` (or `go run gen.go [crate
// directory]`). Without an argument it reads the crate from the Cargo
// registry, where go/port/fetch-reference.sh puts it.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const crateName = "unicode-segmentation-1.13.3"

func main() {
	crate := crateDirectory()
	writeTables(string(read(filepath.Join(crate, "src", "tables.rs"))))
	writeTestdata(string(read(filepath.Join(crate, "tests", "testdata", "mod.rs"))))
}

func crateDirectory() string {
	if len(os.Args) > 1 {
		return os.Args[1]
	}
	home, err := os.UserHomeDir()
	check(err)
	matches, err := filepath.Glob(filepath.Join(home, ".cargo", "registry", "src", "*", crateName))
	check(err)
	if len(matches) == 0 {
		fail("%s is not in the Cargo registry; run go/port/fetch-reference.sh", crateName)
	}
	return matches[0]
}

// rangeTable is a `const NAME: &[(char, char)]` of tables.rs.
type rangeTable struct {
	module string // the `pub mod` holding it
	rust   string
	goName string
}

// categoryTable is one of the modules of tables.rs that map a character to a
// category: a `<prefix>_cat_lookup` index and a `<prefix>_cat_table` of
// `(char, char, Category)`.
type categoryTable struct {
	module     string // grapheme, word, emoji
	lookupType string // the element type of the lookup table
	goModule   string // TablesGrapheme, ...
	goCategory string // the Go type of the category
}

func writeTables(source string) {
	var out bytes.Buffer
	out.WriteString("// Port of unicode-segmentation 1.13.3 src/tables.rs\n")
	out.WriteString("// Code generated by gen.go from the crate's src/tables.rs; DO NOT EDIT.\n\n")
	out.WriteString("// This file holds the property tables of src/tables.rs. The functions that\n")
	out.WriteString("// read them, and the category types, are in tables.go.\n\n")
	out.WriteString("package unicodesegmentation\n\n")
	out.WriteString("import \"github.com/BrokkAi/mjolnir/go/rs\"\n\n")

	for _, table := range []rangeTable{
		{module: "general_category", rust: "N_table", goName: "tablesGeneralCategoryNTable"},
		{module: "derived_property", rust: "Alphabetic_table", goName: "tablesDerivedPropertyAlphabeticTable"},
		{module: "derived_property", rust: "InCB_Extend_table", goName: "tablesDerivedPropertyInCBExtendTable"},
	} {
		body := constBody(moduleBody(source, table.module), table.rust, "&[(char, char)]")
		pair := regexp.MustCompile(`^\('\\u\{([0-9a-f]+)\}','\\u\{([0-9a-f]+)\}'\),?`)
		fmt.Fprintf(&out, "// %s::%s\n", table.module, table.rust)
		fmt.Fprintf(&out, "var %s = []rs.Tuple2[rune, rune]{\n", table.goName)
		rest := compact(body)
		previous := int64(-1)
		count := 0
		for rest != "" {
			match := pair.FindStringSubmatch(rest)
			if match == nil {
				fail("%s: unexpected text %q", table.rust, head(rest))
			}
			lo, hi := hex(match[1]), hex(match[2])
			if lo <= previous || hi < lo {
				fail("%s: ranges are not sorted at %x", table.rust, lo)
			}
			previous = hi
			fmt.Fprintf(&out, "{F0: 0x%x, F1: 0x%x},\n", lo, hi)
			rest = rest[len(match[0]):]
			count++
		}
		out.WriteString("}\n\n")
		fmt.Printf("%s: %d ranges\n", table.rust, count)
	}

	for _, table := range []categoryTable{
		{module: "grapheme", lookupType: "u16", goModule: "tablesGrapheme", goCategory: "tablesGraphemeGraphemeCat"},
		{module: "word", lookupType: "u16", goModule: "tablesWord", goCategory: "tablesWordWordCat"},
		{module: "emoji", lookupType: "u8", goModule: "tablesEmoji", goCategory: "tablesEmojiEmojiCat"},
	} {
		module := moduleBody(source, table.module)

		lookup := compact(constBody(module, table.module+"_cat_lookup", "&["+table.lookupType+"]"))
		goLookupType := map[string]string{"u16": "uint16", "u8": "uint8"}[table.lookupType]
		fmt.Fprintf(&out, "// %s::%s_cat_lookup\n", table.module, table.module)
		fmt.Fprintf(&out, "var %s%sCatLookup = []%s{\n", table.goModule, pascal(table.module), goLookupType)
		entries := strings.Split(lookup, ",")
		for index, entry := range entries {
			if _, err := strconv.ParseUint(entry, 10, 16); err != nil {
				fail("%s_cat_lookup: entry %q", table.module, entry)
			}
			out.WriteString(entry + ",")
			if index%16 == 15 {
				out.WriteByte('\n')
			} else {
				out.WriteByte(' ')
			}
		}
		out.WriteString("\n}\n\n")

		body := compact(constBody(module, table.module+"_cat_table", ""))
		triple := regexp.MustCompile(`^\('\\u\{([0-9a-f]+)\}','\\u\{([0-9a-f]+)\}',([A-Za-z_]+)\),?`)
		fmt.Fprintf(&out, "// %s::%s_cat_table\n", table.module, table.module)
		fmt.Fprintf(&out, "var %s%sCatTable = []rs.Tuple3[rune, rune, %s]{\n", table.goModule, pascal(table.module), table.goCategory)
		previous := int64(-1)
		count := 0
		for body != "" {
			match := triple.FindStringSubmatch(body)
			if match == nil {
				fail("%s_cat_table: unexpected text %q", table.module, head(body))
			}
			lo, hi := hex(match[1]), hex(match[2])
			if lo <= previous || hi < lo {
				fail("%s_cat_table: ranges are not sorted at %x", table.module, lo)
			}
			previous = hi
			fmt.Fprintf(&out, "{F0: 0x%x, F1: 0x%x, F2: %s_%s},\n", lo, hi, table.goCategory, pascal(match[3]))
			body = body[len(match[0]):]
			count++
		}
		out.WriteString("}\n\n")
		fmt.Printf("%s_cat_table: %d ranges, %d lookup entries\n", table.module, count, len(entries))
	}

	formatted, err := format.Source(out.Bytes())
	check(err)
	write("tables_data.go", formatted)
}

// moduleBody returns the text of `pub mod <name> { ... }` at the top level of
// tables.rs.
func moduleBody(source, name string) string {
	marker := "\npub mod " + name + " {\n"
	start := strings.Index(source, marker)
	if start < 0 {
		fail("module %s not found", name)
	}
	rest := source[start+len(marker):]
	end := strings.Index(rest, "\n}\n")
	if end < 0 {
		fail("module %s is not closed", name)
	}
	return rest[:end]
}

// constBody returns the text between the brackets of
// `const <name>: <type> = &[ ... ];`. With an empty type, any type matches.
func constBody(source, name, constType string) string {
	marker := "const " + name + ": "
	start := strings.Index(source, marker)
	if start < 0 || strings.Count(source, marker) != 1 {
		fail("const %s: found %d times", name, strings.Count(source, marker))
	}
	rest := source[start+len(marker):]
	opening := strings.Index(rest, " = &[")
	if opening < 0 {
		fail("const %s has no initializer", name)
	}
	if constType != "" && rest[:opening] != constType {
		fail("const %s has type %q, expected %q", name, rest[:opening], constType)
	}
	rest = rest[opening+len(" = &["):]
	end := strings.Index(rest, "];")
	if end < 0 {
		fail("const %s is not closed", name)
	}
	return rest[:end]
}

// compact removes all white space.
func compact(text string) string {
	return strings.Join(strings.Fields(text), "")
}

func head(text string) string {
	if len(text) > 60 {
		return text[:60]
	}
	return text
}

func hex(digits string) int64 {
	value, err := strconv.ParseInt(digits, 16, 32)
	check(err)
	return value
}

// pascal is the port's case rule (translation-rules.md, rule 2): split on
// `_`, capitalise each part, lower-case the rest of an all-capitals part.
func pascal(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "_") {
		if part == "" {
			continue
		}
		if part == strings.ToUpper(part) {
			part = strings.ToLower(part)
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

// writeTestdata writes the grapheme and word conformance cases of
// tests/testdata/mod.rs as Go tables.
func writeTestdata(source string) {
	var out bytes.Buffer
	out.WriteString("// Port of unicode-segmentation 1.13.3 tests/testdata/mod.rs\n")
	out.WriteString("// Code generated by gen.go from the crate's tests/testdata/mod.rs; DO NOT EDIT.\n\n")
	out.WriteString("// TEST_SENTENCE is not carried over: sentence boundaries are not ported (see\n")
	out.WriteString("// doc.go).\n\n")
	out.WriteString("package unicodesegmentation\n\n")
	out.WriteString("import \"github.com/BrokkAi/mjolnir/go/rs\"\n\n")

	same := parseCases(source, "TEST_SAME", "&[(&str, &[&str])]", 2)
	out.WriteString("// official Unicode test data\n")
	out.WriteString("// http://www.unicode.org/Public/17.0.0/ucd/auxiliary/GraphemeBreakTest.txt\n")
	out.WriteString("var testdataTestSame = []rs.Tuple2[string, []string]{\n")
	for _, c := range same {
		fmt.Fprintf(&out, "{F0: %s, F1: %s},\n", c[0], c[1])
	}
	out.WriteString("}\n\n")

	diff := parseCases(source, "TEST_DIFF", "&[(&str, &[&str], &[&str])]", 3)
	out.WriteString("var testdataTestDiff = []rs.Tuple3[string, []string, []string]{\n")
	for _, c := range diff {
		fmt.Fprintf(&out, "{F0: %s, F1: %s, F2: %s},\n", c[0], c[1], c[2])
	}
	out.WriteString("}\n\n")

	word := parseCases(source, "TEST_WORD", "&[(&str, &[&str])]", 2)
	out.WriteString("// official Unicode test data\n")
	out.WriteString("// http://www.unicode.org/Public/17.0.0/ucd/auxiliary/WordBreakTest.txt\n")
	out.WriteString("var testdataTestWord = []rs.Tuple2[string, []string]{\n")
	for _, c := range word {
		fmt.Fprintf(&out, "{F0: %s, F1: %s},\n", c[0], c[1])
	}
	out.WriteString("}\n")

	fmt.Printf("TEST_SAME: %d cases, TEST_DIFF: %d cases, TEST_WORD: %d cases\n", len(same), len(diff), len(word))
	formatted, err := format.Source(out.Bytes())
	check(err)
	write("it_testdata_test.go", formatted)
}

// parseCases reads `pub const <name>: <type> = &[ (..), (..) ];`, whose
// entries are tuples of a string followed by string slices, and returns each
// entry as Go expressions.
func parseCases(source, name, constType string, fields int) [][]string {
	body := compact(constBody(source, name, constType))
	var cases [][]string
	for body != "" {
		if body[0] != '(' {
			fail("%s: unexpected text %q", name, head(body))
		}
		body = body[1:]
		entry := make([]string, 0, fields)
		for field := 0; field < fields; field++ {
			if field == 0 {
				var literal string
				literal, body = stringLiteral(body, name)
				entry = append(entry, literal)
			} else {
				if !strings.HasPrefix(body, "&[") {
					fail("%s: expected a slice at %q", name, head(body))
				}
				body = body[2:]
				var items []string
				for body[0] != ']' {
					var literal string
					literal, body = stringLiteral(body, name)
					items = append(items, literal)
					body = strings.TrimPrefix(body, ",")
				}
				body = body[1:]
				entry = append(entry, "[]string{"+strings.Join(items, ", ")+"}")
			}
			if field < fields-1 {
				if body[0] != ',' {
					fail("%s: expected `,` at %q", name, head(body))
				}
				body = body[1:]
			}
		}
		if body[0] != ')' {
			fail("%s: expected `)` at %q", name, head(body))
		}
		body = strings.TrimPrefix(body[1:], ",")
		cases = append(cases, entry)
	}
	return cases
}

var escape = regexp.MustCompile(`^\\u\{([0-9a-f]+)\}`)

// stringLiteral reads a Rust string literal made only of `\u{..}` escapes
// from the start of text and returns it as a Go string literal.
func stringLiteral(text, name string) (literal, rest string) {
	if text == "" || text[0] != '"' {
		fail("%s: expected a string at %q", name, head(text))
	}
	text = text[1:]
	var b strings.Builder
	b.WriteByte('"')
	for text[0] != '"' {
		match := escape.FindStringSubmatch(text)
		if match == nil {
			fail("%s: unexpected text in a string at %q", name, head(text))
		}
		value := hex(match[1])
		if value <= 0xFFFF {
			fmt.Fprintf(&b, `\u%04x`, value)
		} else {
			fmt.Fprintf(&b, `\U%08x`, value)
		}
		text = text[len(match[0]):]
	}
	b.WriteByte('"')
	return b.String(), text[1:]
}

func read(path string) []byte {
	data, err := os.ReadFile(path)
	check(err)
	return data
}

func write(path string, data []byte) {
	check(os.MkdirAll(filepath.Dir(path), 0o755))
	check(os.WriteFile(path, data, 0o644))
	fmt.Printf("wrote %s (%d bytes)\n", path, len(data))
}

func check(err error) {
	if err != nil {
		fail("%v", err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen: "+format+"\n", args...)
	os.Exit(1)
}
