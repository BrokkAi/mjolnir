#!/usr/bin/env bash
# Build the Go port's binaries into go/bin. The marker directory tells the
# binaries they are a development build, so they refuse to start, replace,
# stop or migrate the default instance (see EnsureMayControlStore).
#
# It also stamps the build identity, the Go form of mj-build-id/build.rs and
# the image half of mj-core/build.rs. Go records the commit and its time
# itself (vcs.revision and vcs.time, with -buildvcs=true so a checkout whose
# status Go cannot read fails here instead of building without them). This
# script passes the rest with -ldflags -X, and the worker stamp, whose NUL
# bytes no command-line argument can carry, by replacing
# internal/buildid/stamp.go through -overlay.
#
# Environment, as for the Rust build:
#   MJ_BUILD_REVISION     full commit of a source tree without Git
#   MJ_BUILD_COMMIT_TIME  that commit's Unix time (git log -1 --format=%ct)
#   MJ_WORKER_INPUTS_ID   40-digit worker input digest, overriding Git's
#   MJ_BUILD_CHANNEL      "release" for a release build
#   MJ_DAEMON_IMAGE       the daemon image the build names, overriding the channel
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p bin/.mj-development-build

buildid=github.com/BrokkAi/mjolnir/go/internal/buildid
core=github.com/BrokkAi/mjolnir/go/internal/core

fail() {
	echo "build.sh: $*" >&2
	exit 1
}

trim() { # trim <text>: without leading and trailing whitespace, as Rust's str::trim
	local text="$1"
	text="${text#"${text%%[![:space:]]*}"}"
	printf '%s' "${text%"${text##*[![:space:]]}"}"
}

full_digest() { # full_digest <value> <message>: the value in lower case, or fail
	[[ "$1" =~ ^[0-9a-fA-F]{40}$ ]] || fail "$2"
	printf '%s' "$1" | tr 'A-F' 'a-f'
}

go_constant() { # go_constant <name> <file>: a string constant declared in Go source
	local value
	value="$(sed -n "s/^const $1 = \"\\(.*\\)\"\$/\\1/p" "$2")"
	[[ -n "$value" ]] || fail "cannot read $1 from $2"
	printf '%s' "$value"
}

version="$(go_constant PackageVersion internal/core/worker_build.go)"
in_git=false
if git rev-parse --verify --quiet 'HEAD^{commit}' >/dev/null 2>&1; then
	in_git=true
fi

ldflags=()
# The revision: Go reads vcs.revision unless a source tree without Git names
# its commit.
if [[ -n "${MJ_BUILD_REVISION+set}" ]]; then
	revision="$(full_digest "$MJ_BUILD_REVISION" "MJ_BUILD_REVISION must be a full 40-character Git commit")"
	ldflags+=("-X '$buildid.buildRevision=$revision'")
elif ! $in_git; then
	fail "worker build identity needs Git; for a source archive set MJ_BUILD_REVISION to its full Git commit"
fi

# The commit time: Go reads vcs.time, which belongs to HEAD. A named
# revision's time is looked up by its hash, so it is that commit's or
# unknown, never another commit's.
if [[ -n "${MJ_BUILD_COMMIT_TIME+set}" ]]; then
	commit_time="$(trim "$MJ_BUILD_COMMIT_TIME")"
	[[ "$commit_time" =~ ^[+-]?[0-9]+$ ]] ||
		fail "MJ_BUILD_COMMIT_TIME must be the commit's Unix time in seconds"
	ldflags+=("-X '$buildid.buildCommitTime=${commit_time#+}'")
elif [[ -n "${MJ_BUILD_REVISION+set}" ]] && $in_git; then
	if commit_time="$(git show -s --format=%ct "$revision^{commit}" </dev/null 2>/dev/null)"; then
		ldflags+=("-X '$buildid.buildCommitTime=$(trim "$commit_time")'")
	fi
fi

# The worker input digest: the Git tree of this Go module at HEAD, which
# holds every input of the Go worker, so uncommitted changes are not
# reflected, matching the revision. Without Git the commit stands in.
if [[ -n "${MJ_WORKER_INPUTS_ID+set}" ]]; then
	worker_inputs="$(full_digest "$(trim "$MJ_WORKER_INPUTS_ID")" "worker input identity must be a full 40-character digest")"
elif $in_git; then
	worker_inputs="$(full_digest "$(git rev-parse --verify 'HEAD:./')" "worker input identity must be a full 40-character digest")"
else
	worker_inputs="$revision"
fi
ldflags+=("-X '$buildid.workerInputsID=$worker_inputs'")

# A release names its own version's daemon image; keep this one rule for
# both the image and whether that image carries this build's worker.
release=false
if [[ "${MJ_BUILD_CHANNEL-}" == release ]]; then
	release=true
	ldflags+=("-X '$buildid.buildChannel=release'")
fi
if [[ -n "${MJ_DAEMON_IMAGE+set}" ]]; then
	[[ "$MJ_DAEMON_IMAGE" != *"'"* ]] || fail "MJ_DAEMON_IMAGE cannot contain a quote"
	ldflags+=("-X '$core.ReleaseContainerImage=$MJ_DAEMON_IMAGE'")
elif $release; then
	repository="$(go_constant ContainerImageRepository internal/core/config.go)"
	ldflags+=("-X '$core.ReleaseContainerImage=$repository:$version'")
fi

# The worker stamp, as one literal in the executable.
json_string() { # json_string <text>: the text as a JSON string
	local text="${1//\\/\\\\}"
	printf '"%s"' "${text//\"/\\\"}"
}
stamp=bin/.mj-build-stamp
mkdir -p "$stamp"
cat >"$stamp/stamp.go" <<EOF
// Generated by go/scripts/build.sh: the worker stamp of this build.

package buildid

const workerBuildStampLiteral = "\\x00MJ-WORKER-BUILD:$version+$worker_inputs\\x00"
EOF
printf '{"Replace":{%s:%s}}\n' \
	"$(json_string "$PWD/internal/buildid/stamp.go")" \
	"$(json_string "$PWD/$stamp/stamp.go")" >"$stamp/overlay.json"

go build -buildvcs=true -overlay "$stamp/overlay.json" -ldflags "${ldflags[*]}" -o bin/ ./cmd/...
