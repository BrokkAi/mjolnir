#!/usr/bin/env python3
"""Writes assets.go, the root package that embeds every file the Rust code
compiles in with include_str! or include_bytes!.

The Go implementation embeds the same files from the same paths, so the two
implementations cannot disagree about an asset. Run from anywhere:

    python3 go/port/gen_assets.py          # rewrite assets.go
    python3 go/port/gen_assets.py --check  # fail if assets.go is out of date
"""

from __future__ import annotations

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
INCLUDE = re.compile(r'include_(?:str|bytes)!\(\s*"([^"]+)"\s*\)')


def included_files() -> list[str]:
    found = set()
    for crate in sorted(os.listdir(ROOT)):
        if not os.path.isfile(os.path.join(ROOT, crate, "Cargo.toml")):
            continue
        for directory, names, files in os.walk(os.path.join(ROOT, crate)):
            names[:] = [name for name in names if name != "target" and not name.startswith(".")]
            for name in files:
                if not name.endswith(".rs"):
                    continue
                with open(os.path.join(directory, name), encoding="utf-8") as source:
                    text = source.read()
                for match in INCLUDE.finditer(text):
                    target = os.path.normpath(os.path.join(directory, match.group(1)))
                    found.add(os.path.relpath(target, ROOT).replace(os.sep, "/"))
    return sorted(found)


def render(paths: list[str]) -> str:
    lines = [
        "// Code generated by go/port/gen_assets.py. DO NOT EDIT.",
        "",
        "// Package mjolnir embeds the files that the Rust implementation compiles in",
        "// with include_str! and include_bytes!, from the same paths, so that the Go",
        "// implementation ships the same bytes. Use package go/assets to read them.",
        "package mjolnir",
        "",
        'import "embed"',
        "",
        "// Files holds every embedded file under its path from the repository root.",
        "//",
    ]
    lines += [f"//go:embed {path}" for path in paths]
    lines += ["var Files embed.FS", ""]
    return "\n".join(lines)


def main() -> int:
    paths = included_files()
    missing = [path for path in paths if not os.path.isfile(os.path.join(ROOT, path))]
    if missing:
        print("included by Rust but not present:", *missing, sep="\n  ", file=sys.stderr)
        return 1
    text = render(paths)
    target = os.path.join(ROOT, "assets.go")
    if "--check" in sys.argv[1:]:
        current = open(target, encoding="utf-8").read() if os.path.isfile(target) else ""
        if current != text:
            print("assets.go is out of date; run python3 go/port/gen_assets.py", file=sys.stderr)
            return 1
        return 0
    with open(target, "w", encoding="utf-8") as out:
        out.write(text)
    print(f"assets.go: {len(paths)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
