#!/usr/bin/env bash
# Bring the current branch up to date with origin/master and push it, the way
# the Go port needs it done.
#
# The Rust sources keep changing while the port proceeds. A Rust change can
# add or remove a file the code includes with include_str!, and assets.go
# embeds exactly those files, so it is regenerated after every merge. Without
# this the Go lane fails on the first push after such a change.
#
# Upstream is merged, never rebased (AGENTS.md, Git / version control).
#
# Usage: go/port/sync-upstream.sh           # merge, regenerate, push
#        go/port/sync-upstream.sh --no-push
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$root"
branch="$(git rev-parse --abbrev-ref HEAD)"

git fetch --quiet origin
git merge --quiet --no-edit "origin/$branch"

python3 go/port/gen_assets.py >/dev/null
if ! git diff --quiet -- assets.go; then
    git add assets.go
    git commit --quiet -m "Embed the files the Rust code now includes

assets.go lists every file the Rust sources include with include_str!
or include_bytes!. A merge from upstream changed that set; this is the
list regenerated by go/port/gen_assets.py."
    echo "assets.go regenerated"
fi
go build . ./go/assets/

if [ "${1:-}" != "--no-push" ]; then
    git push --quiet origin "HEAD:$branch"
fi
git log -1 --format='%h %s'
